import { test, expect, readAllState, readState, restoreViaUI, catalogFixture, startTrip, selectCatalog } from './fixtures'
import { rc30Fixture } from '../rc30Fixture'
import { readFile } from 'node:fs/promises'

test('RC35 ended trip memo/weather CRUD, exact graph times, collision lanes, toggle, reload and v10 restore', async ({ page }, info) => {
  await restoreViaUI(page, rc30Fixture())
  const before = await readAllState(page)
  await page.getByRole('button', { name: /白馬八方ニレ池/ }).click()
  const memo = page.getByRole('region', { name: '釣行メモ', exact: true })
  await memo.getByRole('textbox').fill('朝はスプーン\n日陰と風の変化を確認')
  await memo.getByRole('button', { name: '釣行メモを保存' }).click()
  await expect(memo.getByRole('status')).toHaveText('保存済み')
  for (let i = 0; i < 2; i++) {
    await page.getByRole('button', { name: '気象を記録', exact: true }).click()
    const editor = page.getByRole('dialog', { name: 'イベント追加', exact: true })
    await editor.getByLabel('発生日時（日本時間）').fill('2026-10-24T10:30')
    if (i) await expect(editor.getByText(/未確認・保存されません/)).toBeVisible()
    await editor.getByRole('button', { name: '🌥️ 日が陰った', exact: true }).click()
    await editor.getByRole('button', { name: '🌬️ 風が強まった', exact: true }).click()
    await editor.getByRole('button', { name: '保存', exact: true }).click()
    await expect(editor).toHaveCount(0)
  }
  const state = await readAllState(page)
  expect(state.tripEvents).toHaveLength(2)
  expect(state.tripEvents[0]!.weatherObservation.changes).toEqual(['sunHidden', 'windStronger'])
  const markers = page.locator('.timeline-marker.weather')
  await expect(markers).toHaveCount(2)
  expect(await markers.first().getAttribute('data-timestamp')).toBe(String(Date.parse('2026-10-24T01:30:00Z')))
  const boxes = await markers.evaluateAll(items => items.map(item => ({ x: item.getBoundingClientRect().x, y: item.getBoundingClientRect().y })))
  expect(boxes[0]!.x).toBe(boxes[1]!.x)
  expect(Math.abs(boxes[0]!.y - boxes[1]!.y)).toBeGreaterThanOrEqual(44)
  const hourly = page.getByRole('region', { name: '釣果グラフの気象イベント', exact: true })
  await expect(hourly.getByRole('button')).toHaveCount(2)
  await hourly.getByRole('button').first().click()
  const detail = page.getByRole('dialog', { name: /気象・環境/ })
  await expect(detail).toContainText('風が強まった')
  await detail.getByRole('button', { name: '記録の詳細を閉じる' }).click()
  await page.getByLabel('気象イベントを表示').uncheck()
  await expect(markers).toHaveCount(0)
  await expect(hourly).toHaveCount(0)
  await page.getByLabel('気象イベントを表示').check()
  await expect(markers).toHaveCount(2)
  const entry = page.locator('.event-entry').first()
  await entry.getByRole('button', { name: '編集', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'イベントを編集', exact: true })
  await editor.getByLabel('発生日時（日本時間）').fill('2026-10-24T11:15')
  await editor.getByRole('button', { name: '☀️ 日が出た', exact: true }).click()
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await expect(editor).toHaveCount(0)
  await expect(page.locator('.timeline-marker.weather[data-timestamp="' + Date.parse('2026-10-24T02:15:00Z') + '"]')).toHaveCount(1)
  await page.screenshot({ path: info.outputPath('rc35-weather-notes.png'), fullPage: true })
  page.once('dialog', d => d.accept())
  await page.locator('.event-entry').first().getByRole('button', { name: '削除', exact: true }).click()
  await expect(markers).toHaveCount(1)
  const expected = await readAllState(page)
  for (const key of Object.keys(before)) if (!['trips', 'tripEvents'].includes(key)) expect(expected[key]).toEqual(before[key])
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await page.reload()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('rc35-v10.json'); await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8')); expect(backup.version).toBe(10)
  await restoreViaUI(page, backup)
  const restored = await readAllState(page)
  for (const key of Object.keys(expected)) if (key !== 'lureMasterImportHistory') expect(restored[key]).toEqual(expected[key])
  await page.getByRole('button', { name: /白馬八方ニレ池/ }).click()
  await expect(memo.getByRole('textbox')).toHaveValue('朝はスプーン\n日陰と風の変化を確認')
})

test('RC35 ongoing independent weather, catch/lost observations and unconfirmed candidates stay optional', async ({ page }) => {
  await restoreViaUI(page, catalogFixture())
  await startTrip(page)
  await page.getByRole('button', { name: '気象を記録', exact: true }).click()
  const event = page.getByRole('dialog', { name: 'イベント追加', exact: true })
  await event.getByRole('button', { name: '☀️ 晴れ', exact: true }).click()
  await event.getByRole('button', { name: '保存', exact: true }).click()
  await expect(event).toHaveCount(0)
  for (const result of ['catch', 'lost', 'plain']) {
    await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
    const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
    if (result === 'lost') {
      await modal.getByRole('button', { name: 'バラシ', exact: true }).click()
      await modal.getByRole('button', { name: '手前', exact: true }).click()
    }
    await modal.getByText('気象・環境を記録（任意）', { exact: true }).click()
    await expect(modal.getByText(/未確認・保存されません/)).toBeVisible()
    if (result !== 'plain') {
      await modal.getByRole('button', { name: '前回の空模様・風を確認して使う' }).click()
      await modal.getByRole('button', { name: '💨 風が吹き始めた', exact: true }).click()
    }
    await selectCatalog(page)
    await modal.getByRole('button', { name: '保存する', exact: true }).click()
    await expect(modal).not.toBeVisible()
  }
  const saved = await readState(page)
  expect(saved.catches.map(c => c.weatherObservation?.source)).toEqual(['observed', 'observed', undefined])
  expect(saved.tripEvents).toHaveLength(1)
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: /釣行を終了/ }).click()
  await page.getByRole('button', { name: /E2Eニレ池/ }).click()
  const history = page.getByRole('region', { name: '釣果履歴' })
  await history.locator('.catch-row').nth(1).getByRole('button', { name: '編集', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await modal.getByText('気象・環境を記録（任意）', { exact: true }).click()
  await modal.getByRole('button', { name: '気象入力をクリア' }).click()
  await modal.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(modal).not.toBeVisible()
  expect((await readState(page)).catches[1]!.weatherObservation).toBeUndefined()
  await expect(page.locator('.timeline-marker.weather')).toHaveCount(2)
})
