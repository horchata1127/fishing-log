import { test, expect, readState } from './fixtures'

test('数値入力のライン新規登録・編集・タブ切替・セット作成・再読込', async ({ page }) => {
  await page.getByRole('button', { name: 'タックル管理', exact: true }).click()
  await page.getByRole('button', { name: '初期候補8件を登録', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('8件追加')
  await page.getByRole('button', { name: 'ライン', exact: true }).click()
  await page.getByLabel('メーカー（任意）', { exact: true }).fill('サンライン')
  await page.getByLabel('製品名（任意）', { exact: true }).fill('鱒ノ糸ナイロン')
  await page.getByLabel('強度（lb）（任意）', { exact: true }).fill('3.5')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('保存しました。')
  let state = await readState(page)
  const added = state.lines.find(row => row.productName === '鱒ノ糸ナイロン')!
  expect(added.strengthLb).toBe(3.5)
  expect(state.lines).toHaveLength(4)
  const article = page.getByRole('article').filter({ hasText: '鱒ノ糸ナイロン' })
  await article.getByRole('button', { name: '編集', exact: true }).click()
  await page.getByLabel('強度（lb）（任意）', { exact: true }).fill('4')
  await page.getByLabel('号数（任意）', { exact: true }).fill('0.8')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('保存しました。')
  await expect(article).toContainText('4lb / 0.8号')
  const beforeInvalid = await readState(page)
  await page.getByLabel('強度（lb）（任意）', { exact: true }).fill('0')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('正の数を入力してください')
  expect(await readState(page)).toEqual(beforeInvalid)
  await page.getByRole('button', { name: 'ロッド', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'ロッド一覧（2件）', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'リール', exact: true }).click()
  const reel = page.getByRole('article').filter({ hasText: 'ヴァンキッシュ' })
  await reel.getByRole('button', { name: '編集', exact: true }).click()
  await page.getByLabel('年式（任意）', { exact: true }).fill('2023')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('保存しました。')
  await page.getByRole('button', { name: 'セット', exact: true }).click()
  for (const name of ['巻の釣り①', '巻の釣り②']) {
    await page.getByLabel('セット名（必須）', { exact: true }).fill(name)
    await page.getByRole('combobox', { name: 'ロッド（必須）', exact: true }).selectOption({ label: 'Palms / クワトロ Universal IV / QFRGS-48XUL' })
    await page.getByRole('combobox', { name: 'リール（必須）', exact: true }).selectOption({ label: 'SHIMANO / ヴァンキッシュ / 2023' })
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('保存しました。')
  }
  await expect(page.getByRole('heading', { name: 'セット一覧（2件）', exact: true })).toBeVisible()
  state = await readState(page)
  expect(state.lines.filter(row => row.id !== added.id)).toEqual(beforeInvalid.lines.filter(row => row.id !== added.id))
  expect(state.reels.find(row => row.modelName === 'ヴァンキッシュ')!.year).toBe(2023)
  await page.reload()
  expect(await readState(page)).toEqual(state)
  await page.getByRole('button', { name: 'タックル管理', exact: true }).click()
  await page.getByRole('button', { name: 'ライン', exact: true }).click()
  await expect(page.getByRole('article').filter({ hasText: '鱒ノ糸ナイロン' })).toContainText('4lb / 0.8号')
  await page.getByRole('button', { name: 'セット', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(2)
})
