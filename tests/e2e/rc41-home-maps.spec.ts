import { test, expect, readAllState, restoreViaUI, type Row } from './fixtures'
import { recordRc41Position } from '../rc41UiHelpers'
import { rc41Fixture } from '../rc41Fixture'
import type { Locator, Page } from '@playwright/test'

async function readMaps(page:Page):Promise<Row[]>{return page.evaluate(async()=>{const path='/fishing-log/src/db/database.ts';const {db}=await import(path);return JSON.parse(JSON.stringify(await db.areaMaps.toArray()))})}
async function addMap(manager:Locator,name:string){
  await manager.getByRole('button',{name:'＋エリアを追加',exact:true}).click()
  await manager.getByLabel('エリアマップ名（必須）',{exact:true}).fill(name)
  await manager.getByLabel('新規エリア名（必須）',{exact:true}).fill(name)
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:`編集：${name}`,exact:true})).toBeVisible()
}

test('RC41 main menu creates and edits maps before any trip, then shares them with a later trip',async({page},info)=>{
  expect((await readAllState(page)).trips).toHaveLength(0)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  const manager=page.getByRole('dialog',{name:'エリアマップ管理',exact:true})
  await expect(manager.getByLabel('釣り場',{exact:true})).toHaveValue('')
  await expect(manager.getByLabel('選択中の施設',{exact:true})).toContainText('未選択')
  await expect(manager.getByRole('button',{name:'＋エリアを追加',exact:true})).toBeDisabled()
  await manager.getByLabel('施設を検索',{exact:true}).fill('日本イワナ')
  await manager.getByLabel('釣り場',{exact:true}).selectOption('official:nihon-iwana-center')
  await expect(manager.getByLabel('選択中の施設',{exact:true})).toContainText('日本イワナセンター')
  await addMap(manager,'事前ポンド')
  const first=(await readMaps(page))[0]!
  expect(first.facilityId).toBe('official:nihon-iwana-center')
  await manager.getByRole('button',{name:'編集：事前ポンド',exact:true}).click()
  await manager.getByRole('button',{name:'左右反転',exact:true}).click()
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：事前ポンド',exact:true})).toBeVisible()
  const edited=(await readMaps(page))[0]!
  expect(edited.id).toBe(first.id);expect(edited.zoneId).toBe(first.zoneId);expect(edited.revision).toBe(first.revision+1)
  expect((await readAllState(page)).trips).toHaveLength(0)
  expect((await readAllState(page)).tripEvents).toHaveLength(0)
  await manager.screenshot({path:info.outputPath('rc41-home-manager.png')})
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  await expect(page.getByRole('heading',{name:'🎣 Fishing Log',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'新しい釣行を開始'}).click()
  await page.getByLabel('管理釣り場',{exact:true}).selectOption('official:nihon-iwana-center')
  await page.getByRole('button',{name:'🎣 釣行開始',exact:true}).click()
  await recordRc41Position(page,'事前ポンド')
  expect((await readAllState(page)).tripEvents![0]!.fishingPosition.mapId).toBe(first.id)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  await manager.getByRole('button',{name:'編集：事前ポンド',exact:true}).click()
  await manager.getByLabel('エリアマップ名（必須）',{exact:true}).fill('現地で更新')
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：現地で更新',exact:true})).toBeVisible()
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  await expect(page.getByRole('button',{name:'🎣 釣れた！',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'← ホーム',exact:true}).click()
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  await manager.getByLabel('釣り場',{exact:true}).selectOption('official:nihon-iwana-center')
  await expect(manager.getByRole('button',{name:'編集：現地で更新',exact:true})).toBeVisible()
  expect((await readMaps(page))[0]!.id).toBe(first.id)
})

test('RC41 main-menu map work preserves existing trips/catches/events and keeps facility results separate',async({page})=>{
  await restoreViaUI(page,rc41Fixture())
  const before=await readAllState(page)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  const manager=page.getByRole('dialog',{name:'エリアマップ管理',exact:true})
  await manager.getByLabel('施設を検索',{exact:true}).fill('RC41合成')
  await manager.getByLabel('釣り場',{exact:true}).selectOption('user:rc41-f')
  await addMap(manager,'ユーザー施設のポンド')
  await manager.getByLabel('施設を検索',{exact:true}).fill('存在しない名前')
  await expect(manager.getByLabel('選択中の施設',{exact:true})).toContainText('RC41合成施設')
  await expect(manager.getByText('該当する施設がありません。検索条件を変更してください。')).toBeVisible()
  await manager.getByLabel('施設を検索',{exact:true}).fill('日本イワナ')
  await manager.getByLabel('釣り場',{exact:true}).selectOption('official:nihon-iwana-center')
  await expect(manager.getByRole('button',{name:'編集：ユーザー施設のポンド',exact:true})).toHaveCount(0)
  await expect(manager.getByText('この釣り場にはマップがありません。')).toBeVisible()
  await manager.getByLabel('施設を検索',{exact:true}).fill('RC41合成')
  await manager.getByLabel('釣り場',{exact:true}).selectOption('user:rc41-f')
  await expect(manager.getByRole('button',{name:'編集：ユーザー施設のポンド',exact:true})).toBeVisible()
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  const after=await readAllState(page)
  for(const key of ['trips','catches','tripEvents','myLures','lureModels','lureVariants'])expect(after[key]).toEqual(before[key])
})
