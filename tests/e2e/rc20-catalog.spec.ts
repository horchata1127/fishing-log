import { readFile } from 'node:fs/promises'
import { test, expect, readState, restoreViaUI } from './fixtures'
import { rc20Fixture } from '../rc20Fixture'

test('RC20事前確認・キャンセル・48色追加・30色表示・再実行・バックアップ復元', async ({ page }, info) => {
  await restoreViaUI(page, rc20Fixture())
  const before = await readState(page)
  const check = page.getByRole('button', { name: 'RC20の追加予定を確認', exact: true })
  const preview = page.getByRole('region', { name: 'RC20カタログの事前確認', exact: true })
  await check.click()
  await expect(preview).toContainText('追加 48色・登録済み 2色・保留 282色')
  expect(await readState(page)).toEqual(before)
  const diffDownload = page.waitForEvent('download')
  await preview.getByRole('button', { name: '照合結果をCSVで保存', exact: true }).click()
  const diffPath = info.outputPath('rc20-device-diff.csv')
  await (await diffDownload).saveAs(diffPath)
  const csv = await readFile(diffPath, 'utf8')
  expect(csv).toContain('"1887","keep"')
  expect(csv).toContain('"1888","keep"')
  await preview.getByRole('button', { name: 'RC20の追加をキャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(before)
  await check.click()
  await preview.getByRole('button', { name: 'RC20の確認済みカラーを追加', exact: true }).click()
  await expect(preview).not.toBeVisible()
  const saved = await readState(page)
  expect(saved.catches).toEqual(before.catches)
  expect(saved.trips).toEqual(before.trips)
  expect(saved.myLures).toEqual(before.myLures)
  expect(saved.lureManufacturers).toEqual(before.lureManufacturers)
  expect(saved.lureSeries).toEqual(before.lureSeries)
  expect(saved.lureModels).toEqual(before.lureModels)
  expect(saved.lureVariants.filter(v => v.modelId === 305)).toHaveLength(30)
  expect(saved.lureVariants.find(v => v.id === 1887)).toEqual(before.lureVariants.find(v => v.id === 1887))
  expect(saved.lureVariants.find(v => v.id === 1888)).toEqual(before.lureVariants.find(v => v.id === 1888))
  await check.click()
  await expect(preview).toContainText('追加 0色・登録済み 50色・保留 282色')
  await expect(preview.getByRole('button', { name: 'RC20の確認済みカラーを追加', exact: true })).toBeDisabled()
  await preview.getByRole('button', { name: 'RC20の追加をキャンセル', exact: true }).click()
  await page.reload()
  expect(await readState(page)).toEqual(saved)
  const backupDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()
  const path = info.outputPath('rc20-backup.json')
  await (await backupDownload).saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8'))
  for (const [table, rows] of Object.entries(saved)) {
    if (table in backup.data) expect(backup.data[table]).toEqual(rows)
    else expect(rows).toEqual([]) // Legacy-compatible export omits empty optional tables.
  }
  await restoreViaUI(page, backup)
  expect(await readState(page)).toEqual(saved)
  await page.getByRole('button', { name: /合成巾着田/ }).click()
  await page.getByRole('region', { name: '釣果履歴' }).getByRole('button', { name: '編集', exact: true }).first().click()
  const modal = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await modal.getByRole('button', { name: '変更', exact: true }).click()
  const picker = page.getByRole('dialog', { name: 'ルアーを選択', exact: true })
  await picker.getByRole('button', { name: 'カタログ', exact: true }).click()
  await picker.getByLabel('モデルを選んでからカラーを選択').selectOption('305')
  await expect(picker.getByRole('button', { name: /^HUNT GRANDE 1\.3g T-/ })).toHaveCount(30)
  await expect(picker.getByRole('button', { name: /T-30 鬼鮫/ })).toBeVisible()
  await picker.getByRole('button', { name: '✕', exact: true }).click()
  await modal.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(saved)
})
