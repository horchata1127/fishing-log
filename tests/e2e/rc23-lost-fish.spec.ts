import { readFile } from 'node:fs/promises'
import { test, expect, readState, restoreViaUI, startTrip, catalogFixture, selectCatalog } from './fixtures'
import { rc23Fixture } from '../rc23Fixture'

test('RC23 automatically owns catalog catch/lost once, excludes manual input, and retains ownership after editing/deleting', async ({ page }) => {
  await restoreViaUI(page, catalogFixture())
  await startTrip(page)
  const before = await readState(page)
  const dialog = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  for (const result of ['lost', 'lost', 'catch']) {
    await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
    if (result === 'lost') {
      await dialog.getByRole('button', { name: 'バラシ', exact: true }).click()
      await dialog.getByRole('button', { name: '沖', exact: true }).click()
    }
    await selectCatalog(page)
    await dialog.getByRole('button', { name: '保存する', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  const saved = await readState(page)
  const owned = saved.myLures.filter(r => r.ownershipStatus === 'owned')
  expect(owned).toHaveLength(1)
  expect(saved.myLures.filter(r => r.id <= 52)).toEqual(before.myLures)
  expect(saved.catches.every(r => r.lureId === owned[0].id && r.lureVariantId === 40)).toBe(true)
  await expect(page.getByText('キャッチ 1匹／バラシ 2回', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await dialog.getByRole('button', { name: 'バラシ', exact: true }).click()
  await dialog.getByRole('button', { name: '手前', exact: true }).click()
  await dialog.getByRole('button', { name: '手入力する' }).click()
  await dialog.getByLabel('ルアー名', { exact: true }).fill('E2Eスプーン')
  await dialog.getByLabel('カラー', { exact: true }).fill('赤')
  await dialog.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect((await readState(page)).myLures).toEqual(saved.myLures)
  const history = page.getByRole('region', { name: '釣果履歴' })
  await history.getByRole('button', { name: '編集', exact: true }).first().click()
  const editing = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await editing.getByRole('button', { name: 'キャッチ', exact: true }).click()
  await editing.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(editing).not.toBeVisible()
  const accept = page.waitForEvent('dialog').then(d => d.accept())
  await history.getByRole('button', { name: '削除', exact: true }).nth(1).click(); await accept
  await expect(page.getByText('キャッチ 1匹／バラシ 2回', { exact: true })).toBeVisible()
  expect((await readState(page)).myLures).toEqual(saved.myLures)
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await page.getByRole('button', { name: '🎣 マイルアー', exact: true }).click()
  await expect(page.getByRole('region', { name: '所有ルアー' })).toContainText('キャッチ 0匹／バラシ 2回')
})

test('RC23 separates catches/lost distances, preserves RC22, supports editing/deletion and backup', async ({ page }) => {
  await restoreViaUI(page, rc23Fixture())
  const before = await readState(page)
  expect(before.catches).toHaveLength(7)
  expect(before.catches.filter(r => r.resultType === 'lost')).toHaveLength(0)
  expect(before.myLures).toHaveLength(4)
  expect(before.lureVariants).toHaveLength(2307)
  await startTrip(page)
  const dialog = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  const open = () => page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await open()
  await dialog.getByRole('button', { name: 'バラシ', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '保存する', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect((await readState(page)).catches).toEqual(before.catches)
  for (const distance of ['沖', '手前', 'キャッチ直前']) {
    await open()
    await dialog.getByRole('button', { name: 'バラシ', exact: true }).click()
    await dialog.getByRole('button', { name: distance, exact: true }).click()
    await dialog.getByRole('combobox', { name: '魚種を選択', exact: true }).selectOption('')
    await dialog.getByRole('button', { name: 'ルアーを選ぶ' }).click()
    await page.getByRole('dialog', { name: 'ルアーを選択', exact: true }).getByRole('button', { name: /HUNT GRANDE 1.3g.*T-15/ }).first().click()
    await dialog.getByRole('button', { name: 'キャッチ', exact: true }).click()
    await dialog.getByRole('button', { name: 'バラシ', exact: true }).click()
    await expect(dialog.getByRole('button', { name: distance, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await dialog.getByRole('button', { name: '保存する', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'バラシ登録完了' })).toBeVisible()
  }
  await expect(page.getByText('キャッチ 0匹／バラシ 3回', { exact: true })).toBeVisible()
  const saved = await readState(page)
  expect(saved.catches.filter(r => r.resultType === 'lost').map(r => r.lostDistance).sort()).toEqual(['landing', 'near', 'offshore'])
  expect(saved.catches.filter(r => r.resultType === 'lost').every(r => r.lureId && r.lureVariantId)).toBe(true)
  for (const name of Object.keys(before)) {
    if (name === 'trips' || name === 'catches') continue
    expect(saved[name as keyof typeof saved]).toEqual(before[name as keyof typeof before])
  }
  for (const row of before.catches) expect(saved.catches.find(r => r.id === row.id)).toEqual(row)
  for (const row of before.trips) expect(saved.trips.find(r => r.id === row.id)).toEqual(row)
  await open()
  await dialog.getByRole('button', { name: '保存する', exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
  await expect(page.getByText('キャッチ 1匹／バラシ 3回', { exact: true })).toBeVisible()
  const history = page.getByRole('region', { name: '釣果履歴' })
  await history.getByRole('button', { name: '編集', exact: true }).nth(1).click()
  const editing = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await editing.getByRole('button', { name: 'キャッチ', exact: true }).click()
  await editing.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(page.getByText('キャッチ 2匹／バラシ 2回', { exact: true })).toBeVisible()
  await history.getByRole('button', { name: '編集', exact: true }).nth(1).click()
  await editing.getByRole('button', { name: 'バラシ', exact: true }).click()
  await expect(editing.getByRole('button', { name: '保存する', exact: true })).toBeDisabled()
  await editing.getByRole('button', { name: '手前', exact: true }).click()
  await editing.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(page.getByText('キャッチ 1匹／バラシ 3回', { exact: true })).toBeVisible()
  const dismiss = page.waitForEvent('dialog').then(d => d.dismiss())
  await history.getByRole('button', { name: '削除', exact: true }).first().click(); await dismiss
  expect((await readState(page)).catches).toHaveLength(11)
  const accept = page.waitForEvent('dialog').then(d => d.accept())
  await history.getByRole('button', { name: '削除', exact: true }).first().click(); await accept
  await expect(page.getByText('キャッチ 0匹／バラシ 3回', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await page.getByRole('button', { name: '🎣 マイルアー', exact: true }).click()
  const owned = page.getByRole('region', { name: '所有ルアー' })
  await expect(owned.getByRole('article').filter({ hasText: 'T-15' }).first()).toContainText('バラシ 3回')
  await page.getByRole('button', { name: '← 戻る', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()
  const backup = JSON.parse(await readFile((await (await download).path())!, 'utf8'))
  const final = await readState(page)
  await restoreViaUI(page, backup)
  expect(await readState(page)).toEqual(final)
})
