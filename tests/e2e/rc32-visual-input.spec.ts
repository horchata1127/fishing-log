import { readFile } from 'node:fs/promises'
import { test, expect, catalogFixture, readState, restoreViaUI, startTrip, selectCatalog, saveCatch } from './fixtures'

test('仮配色を3色まで入力し、模様・属性・編集・前回・バックアップを保持する', async ({ page }, info) => {
  await startTrip(page)
  const before = await readState(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  const editor = modal.getByRole('region', { name: 'ビジュアルカラー入力' })
  await expect(editor.locator('.swatches button')).toHaveCount(48)
  await expect(editor.getByLabel('模様', { exact: true })).not.toBeVisible()
  await editor.getByRole('button', { name: 'レッド', exact: true }).click()
  await expect(editor.getByRole('img', { name: '配色プレビュー' }).locator('g[data-region="whole"] > rect')).toHaveAttribute('fill', '#FF0000')
  await editor.getByRole('button', { name: 'ブルー', exact: true }).click()
  await editor.getByRole('button', { name: 'ゴールド', exact: true }).click()
  await editor.getByRole('button', { name: 'ホワイト', exact: true }).click()
  await expect(editor.getByRole('status')).toContainText('最大3色')
  await expect(editor.getByRole('button', { name: 'ホワイト', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await editor.getByText('模様・特殊属性・部位設定', { exact: true }).click()
  await editor.getByLabel('模様', { exact: true }).selectOption('spots')
  await expect(editor.locator('g[data-region="whole"]')).toHaveAttribute('data-pattern', 'spots')
  await editor.getByRole('button', { name: 'グロー', exact: true }).click()
  await editor.getByRole('button', { name: 'ラメ', exact: true }).click()
  await saveCatch(page)
  const saved = await readState(page)
  expect(saved.myLures).toEqual(before.myLures)
  expect(saved.lureVariants).toEqual(before.lureVariants)
  const snapshot = saved.catches[0]!.visualColorSnapshot
  expect(snapshot.appearance.regions.whole).toEqual({ colors: ['red', 'blue', 'gold'], attributes: ['glow', 'glitter'], pattern: 'spots' })
  const history = page.getByRole('region', { name: '釣果履歴' })
  await expect(history.getByRole('img', { name: '配色プレビュー' })).toHaveCount(1)
  await history.getByRole('button', { name: '編集', exact: true }).click()
  const editing = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await editing.getByLabel('メモ（任意）').fill('配色を保持')
  await editing.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(editing).not.toBeVisible()
  expect((await readState(page)).catches[0]!.visualColorSnapshot).toEqual(snapshot)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await modal.getByRole('button', { name: /前回と同じ/ }).click()
  await expect(modal).not.toBeVisible()
  expect((await readState(page)).catches.map(c => c.visualColorSnapshot)).toEqual([snapshot, snapshot])
  await history.getByRole('button', { name: '編集', exact: true }).first().click()
  const editColor = editing.getByRole('region', { name: 'ビジュアルカラー入力' })
  await editColor.getByRole('button', { name: 'ブルー', exact: true }).click()
  await editing.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect((await readState(page)).catches.map(c => c.visualColorSnapshot)).toEqual([snapshot, snapshot])
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('synthetic-rc32-v8.json'); await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8'))
  expect(backup.version).toBe(8)
  const beforeRestore = await readState(page)
  await restoreViaUI(page, backup)
  expect(await readState(page)).toEqual(beforeRestore)
})

test('スプーンは表裏、ミノーとクランクは背側腹、未指定部位を補完しない', async ({ page }) => {
  const fixture = catalogFixture()
  await restoreViaUI(page, fixture)
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await selectCatalog(page)
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  const editor = modal.getByRole('region', { name: 'ビジュアルカラー入力' })
  await expect(editor.getByRole('button', { name: '表', exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'レッド', exact: true }).click()
  await saveCatch(page)
  expect((await readState(page)).catches[0]!.visualColorSnapshot.appearance.regions).toEqual({ front: { colors: ['red'], attributes: [] } })
  for (const category of ['ミノー', 'クランク']) {
    fixture.data.lureModels[0]!.category = category
    await page.getByRole('button', { name: '← ホーム', exact: true }).click()
    await restoreViaUI(page, fixture)
    await startTrip(page)
    await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
    await selectCatalog(page)
    await expect(editor.getByRole('button', { name: '背', exact: true })).toBeVisible()
    await expect(editor.getByRole('button', { name: '腹', exact: true })).toBeVisible()
    await editor.getByRole('button', { name: '側', exact: true }).click()
    await editor.getByRole('button', { name: 'シルバー', exact: true }).click()
    await saveCatch(page)
    expect((await readState(page)).catches[0]!.visualColorSnapshot.appearance.regions).toEqual({ side: { colors: ['silver'], attributes: [] } })
  }
})

test('5種類の模様と12属性を選択し、部位のクリアと配色削除を保存できる', async ({ page }) => {
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  const editor = modal.getByRole('region', { name: 'ビジュアルカラー入力' })
  await editor.getByText('模様・特殊属性・部位設定', { exact: true }).click()
  await editor.getByLabel('部位構成').selectOption('spoon')
  await editor.getByRole('button', { name: 'レッド', exact: true }).click()
  await editor.getByRole('button', { name: 'ブルー', exact: true }).click()
  for (const pattern of ['single', 'two-tone', 'gradient', 'spots', 'marble']) {
    await editor.getByLabel('模様', { exact: true }).selectOption(pattern)
    await expect(editor.locator('g[data-region="front"]')).toHaveAttribute('data-pattern', pattern)
  }
  const attributes = editor.locator('.attribute-grid button')
  await expect(attributes).toHaveCount(12)
  for (const button of await attributes.all()) await button.click()
  await editor.getByRole('button', { name: '裏', exact: true }).click()
  await editor.getByRole('button', { name: 'ブラック', exact: true }).click()
  await editor.getByRole('button', { name: 'この部位を未指定にする', exact: true }).click()
  await saveCatch(page)
  const stored = (await readState(page)).catches[0]!.visualColorSnapshot
  expect(stored.appearance.regions.front.attributes).toHaveLength(12)
  expect(stored.appearance.regions).not.toHaveProperty('back')
  const history = page.getByRole('region', { name: '釣果履歴' })
  await history.getByRole('button', { name: '編集', exact: true }).click()
  const editing = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await editing.getByText('模様・特殊属性・部位設定', { exact: true }).click()
  await editing.getByRole('button', { name: '配色をすべてクリア', exact: true }).click()
  await editing.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(editing).not.toBeVisible()
  expect((await readState(page)).catches[0]).not.toHaveProperty('visualColorSnapshot')
  expect((await readState(page)).myLures).toEqual([])
})
