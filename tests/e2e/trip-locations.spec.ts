import { test, expect, readState, saveCatch, type Row } from './fixtures'
import type { Page, Locator } from '@playwright/test'

// Test-only origin and fresh BrowserContext; all facilities below are fictional.
const databaseModule = '/fishing-log/src/db/database.ts'
async function state(page: Page): Promise<Record<string, Row[]>> {
  return page.evaluate(async module => {
    const { db } = await import(module)
    return JSON.parse(JSON.stringify(Object.fromEntries(await Promise.all(db.tables.map(async (t: any) => [t.name, await t.toArray()])))))
  }, databaseModule)
}
async function add(group: Locator, kind: 'facility' | 'zone', name: string) {
  await group.getByRole('button', { name: kind === 'facility' ? '施設を追加' : 'この施設にエリアを追加', exact: true }).click()
  await group.getByLabel(kind === 'facility' ? '追加する施設名' : '追加するエリア名', { exact: true }).fill(name)
  await group.getByRole('button', { name: '登録して選択', exact: true }).click()
  await expect(group.getByRole('button', { name: '登録して選択', exact: true })).not.toBeVisible()
}
async function startLocated(page: Page) {
  await page.getByRole('button', { name: '新しい釣行を開始' }).click()
  const group = page.getByRole('group', { name: '管理釣り場・エリア（任意）', exact: true })
  await add(group, 'facility', '架空ユーザー施設')
  await add(group, 'zone', '下池')
  await page.getByRole('button', { name: '🎣 釣行開始', exact: true }).click()
  await expect(page.getByRole('button', { name: '🎣 釣れた！', exact: true })).toBeVisible()
}

test('no official rows: free text survives select/clear, canceled additions write nothing, facility-only catch works', async ({ page }) => {
  await page.getByRole('button', { name: '新しい釣行を開始' }).click()
  const group = page.getByRole('group', { name: '管理釣り場・エリア（任意）', exact: true })
  await expect(group).toContainText('自由入力でも開始できます')
  await page.getByLabel('釣り場', { exact: true }).fill('架空の河川')
  await group.getByRole('button', { name: '施設を追加', exact: true }).click()
  await group.getByLabel('追加する施設名', { exact: true }).fill('未保存施設')
  await expect(page.getByRole('button', { name: '🎣 釣行開始', exact: true })).toBeDisabled()
  await group.getByRole('button', { name: '追加をキャンセル', exact: true }).click()
  expect((await state(page)).facilities).toEqual([])
  await add(group, 'facility', '架空エリアなし施設')
  await expect(group.getByLabel('管理釣り場', { exact: true })).toContainText('ユーザー登録')
  await group.getByLabel('管理釣り場', { exact: true }).selectOption('')
  await expect(page.getByLabel('釣り場', { exact: true })).toHaveValue('架空の河川')
  await group.getByLabel('施設を検索', { exact: true }).fill('エリアなし')
  await group.getByLabel('管理釣り場', { exact: true }).selectOption({ label: '架空エリアなし施設（ユーザー登録）' })
  await expect(group.getByLabel('エリア（任意）', { exact: true }).locator('option')).toHaveCount(1)
  await page.getByRole('button', { name: '🎣 釣行開始', exact: true }).click()
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click(); await saveCatch(page)
  const saved = await readState(page)
  expect(saved.catches[0]!.zoneId).toBeUndefined()
  expect(saved.catches[0]!.locationSnapshot).toEqual({ facilityName: '架空エリアなし施設' })
})

test('current zone, previous shortcut, per-catch override/clear, cancel and reload preserve snapshots', async ({ page }, info) => {
  await startLocated(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click(); await saveCatch(page)
  let current = page.getByRole('group', { name: '現在のエリア', exact: true })
  await add(current, 'zone', '上池')
  await expect(current.getByLabel('現在のエリア', { exact: true })).toHaveValue((await state(page)).zones.find(z => z.name === '上池')!.id)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  let modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: /前回と同じ/ }).click(); await expect(modal).not.toBeVisible()
  expect((await state(page)).catches.map(r => r.locationSnapshot.zoneName)).toEqual(['下池', '上池'])
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await modal.getByLabel('今回のエリア', { exact: true }).selectOption({ label: '下池（ユーザー登録）' })
  await saveCatch(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await modal.getByLabel('今回のエリア', { exact: true }).selectOption(''); await saveCatch(page)
  const saved = await state(page)
  expect(saved.catches.map(r => r.locationSnapshot.zoneName)).toEqual(['下池', '上池', '下池', undefined])
  expect(saved.trips[0]!.currentZoneId).toBe(saved.zones.find(z => z.name === '上池')!.id)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await modal.getByRole('button', { name: 'この施設にエリアを追加', exact: true }).click()
  await modal.getByLabel('追加するエリア名', { exact: true }).fill('未保存池')
  await expect(modal.getByRole('button', { name: '保存する', exact: true })).toBeDisabled()
  await modal.getByRole('button', { name: '追加をキャンセル', exact: true }).click()
  await modal.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect(await state(page)).toEqual(saved)
  await expect(page.getByText('架空ユーザー施設 / 下池', { exact: true }).first()).toBeVisible()
  await page.screenshot({ path: info.outputPath('location-history.png'), fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: /架空ユーザー施設/ }).click()
  current = page.getByRole('group', { name: '現在のエリア', exact: true })
  await expect(current.getByLabel('現在のエリア', { exact: true })).toHaveValue(saved.trips[0]!.currentZoneId)
  expect(await state(page)).toEqual(saved)
})

