test('retired current remains usable, disappears after clear; official labels and ended readonly are visible', async ({ page }) => {
  await page.evaluate(async module => {
    const { db } = await import(module)
    const { applyFacilityMaster } = await import(String('/fishing-log/src/utils/facilityStorage.ts'))
    const facility = { id: 'official:test-f', name: '架空公式施設', prefecture: '長野県', address: null, facilityTypes: ['pond'], lureAllowed: true,
      operationStatus: 'open', officialUrl: null, sourceUrl: null, verifiedAt: null, aliases: [], zones: [{ id: 'official:test-z', name: '旧池', sortOrder: 1, sourceUrl: null }] }
    const master = (releaseOrder: number, facilities: any[]) => ({ schemaVersion: 1, masterVersion: `test-${releaseOrder}`, distributionMode: 'full', releaseOrder, facilities })
    await applyFacilityMaster(master(1, [facility]))
    await db.trips.add({ fishingAreaName: '継続試験', fishingDate: '2026-10-11', startedAt: new Date(), facilityId: facility.id, currentZoneId: 'official:test-z' })
    await applyFacilityMaster(master(2, [{ ...facility, id: 'official:other', zones: [] }]))
  }, databaseModule)
  await page.reload(); await page.getByRole('button', { name: /継続試験/ }).click()
  const current = page.getByRole('group', { name: '現在のエリア', exact: true })
  await expect(current).toContainText('退役済み・継続中')
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click(); await saveCatch(page)
  expect((await state(page)).catches[0]!.zoneId).toBe('official:test-z')
  await current.getByLabel('現在のエリア', { exact: true }).selectOption('')
  await expect(current.getByLabel('現在のエリア', { exact: true }).locator('option')).toHaveCount(1)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '釣行を終了', exact: true }).click()
  await page.getByRole('button', { name: /継続試験/ }).click()
  await expect(current.getByLabel('現在のエリア', { exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '🎣 釣れた！', exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await page.getByRole('button', { name: '新しい釣行を開始' }).click()
  const choices = page.getByLabel('管理釣り場', { exact: true })
  await expect(choices).not.toContainText('退役済み')
  await expect(choices).toContainText('公式')
})

test('concurrent current-zone change rejects stale modal without losing input or creating owned lure', async ({ page }) => {
  await startLocated(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByLabel('全長（cm・任意）', { exact: true }).fill('30')
  await page.evaluate(async module => {
    const { db } = await import(module), row = (await db.trips.toArray())[0]
    const { changeCurrentZone } = await import(String('/fishing-log/src/utils/tripLocations.ts'))
    await changeCurrentZone(row.id, undefined, row.currentZoneId)
  }, databaseModule)
  const before = await state(page)
  const message = page.waitForEvent('dialog'); await modal.getByRole('button', { name: '保存する', exact: true }).click()
  const dialog = await message; expect(dialog.message()).toContain('別の画面'); await dialog.accept()
  await expect(modal.getByLabel('全長（cm・任意）', { exact: true })).toHaveValue('30')
  expect(await state(page)).toEqual(before)
  await modal.getByRole('button', { name: 'キャンセル', exact: true }).click()
})
