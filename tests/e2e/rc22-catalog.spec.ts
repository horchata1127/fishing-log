import { readFile } from 'node:fs/promises'
import { test, expect, readState, restoreViaUI } from './fixtures'
import { rc22Fixture } from '../rc22Fixture'

test('RC22 preview, CSV, cancellation, 89 additions, historical preservation, repeat and backup restoration', async ({ page }, info) => {
  await restoreViaUI(page, rc22Fixture())
  const before = await readState(page)
  expect(before.lureVariants).toHaveLength(2218)
  expect(before.catches).toHaveLength(7)
  expect(before.myLures).toHaveLength(4)
  const check = page.getByRole('button', { name: 'RC22の追加予定を確認', exact: true })
  const preview = page.getByRole('region', { name: 'RC22カタログの事前確認', exact: true })
  await check.click()
  await expect(preview).toContainText('追加 89色・登録済み 0色・保留 11行')
  await expect(preview).toContainText('新しいモデル 8件・シリーズ 4件')
  await expect(preview.getByRole('list', { name: 'RC22モデル別の状態' })).toContainText('0.7g')
  expect(await readState(page)).toEqual(before)
  const download = page.waitForEvent('download')
  await preview.getByRole('button', { name: '照合結果をCSVで保存', exact: true }).click()
  const path = info.outputPath('rc22-device-diff.csv')
  await (await download).saveAs(path)
  const csv = await readFile(path, 'utf8')
  expect(csv.trim().split('\n')).toHaveLength(119)
  expect(csv).toContain('manufacturer_id,series_id,model_id,existing_id')
  expect(csv).toContain('https://rob-lure.com/')
  await preview.getByRole('button', { name: 'RC22の追加をキャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(before)
  await check.click()
  await preview.getByRole('button', { name: 'RC22の確認済みカタログを追加', exact: true }).click()
  await expect(preview).not.toBeVisible()
  const saved = await readState(page)
  for (const [table, rows] of Object.entries(before)) {
    const records = saved[table as keyof typeof saved]
    for (const row of rows) expect(records.find(r => (r.id ?? r.fish_id) === (row.id ?? row.fish_id))).toEqual(row)
    if (!['lureSeries', 'lureModels', 'lureVariants'].includes(table)) expect(records).toEqual(rows)
  }
  expect(saved.lureVariants.length - before.lureVariants.length).toBe(89)
  expect(saved.lureModels.length - before.lureModels.length).toBe(8)
  expect(saved.lureSeries.length - before.lureSeries.length).toBe(4)
  await check.click()
  await expect(preview).toContainText('追加 0色・登録済み 89色・保留 11行')
  await expect(preview.getByRole('button', { name: 'RC22の確認済みカタログを追加', exact: true })).toBeDisabled()
  await preview.getByRole('button', { name: 'RC22の追加をキャンセル', exact: true }).click()
  await page.reload()
  expect(await readState(page)).toEqual(saved)
  const backupDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()
  const backupPath = info.outputPath('rc22-backup.json')
  await (await backupDownload).saveAs(backupPath)
  const backup = JSON.parse(await readFile(backupPath, 'utf8'))
  for (const [table, rows] of Object.entries(saved)) {
    if (table in backup.data) expect(backup.data[table]).toEqual(rows)
    else expect(rows).toEqual([])
  }
  await restoreViaUI(page, backup)
  expect(await readState(page)).toEqual(saved)
  // The catalog is selectable from a historical catch without auto-owning it.
  await page.getByRole('button', { name: /合成巾着田/ }).first().click()
  await page.getByRole('region', { name: '釣果履歴' }).getByRole('button', { name: '編集', exact: true }).first().click()
  const editor = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await editor.getByRole('button', { name: '変更', exact: true }).click()
  const picker = page.getByRole('dialog', { name: 'ルアーを選択', exact: true })
  await picker.getByRole('button', { name: 'カタログ', exact: true }).click()
  const barbieF = saved.lureModels.find(m => m.name === 'バービー F')!
  await picker.getByLabel('モデルを選んでからカラーを選択').selectOption(String(barbieF.id))
  await expect(picker.getByRole('button', { name: /^バービー F / })).toHaveCount(14)
  await picker.getByRole('button', { name: '✕', exact: true }).click()
  await editor.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(saved)
})

test('RC22 cross-tab concurrent confirmation commits once and preserves the RC21 baseline', async ({ page, context }) => {
  await restoreViaUI(page, rc22Fixture())
  const before = await readState(page)
  const other = await context.newPage()
  await other.goto('/fishing-log/')
  for (const p of [page, other]) await p.getByRole('button', { name: 'RC22の追加予定を確認', exact: true }).click()
  await Promise.all([page, other].map(p => p.getByRole('button', { name: 'RC22の確認済みカタログを追加', exact: true }).click()))
  await expect.poll(async () => (await readState(page)).lureVariants.length).toBe(2307)
  await expect.poll(async () => (await page.getByRole('status').allTextContents()).join(' ') + (await other.getByRole('status').allTextContents()).join(' ')).toContain('もう一度事前確認')
  const saved = await readState(page)
  expect(saved.catches).toEqual(before.catches)
  expect(saved.myLures).toEqual(before.myLures)
  expect(saved.lureModels.length - before.lureModels.length).toBe(8)
  expect(saved.lureSeries.length - before.lureSeries.length).toBe(4)
  await other.close()
})
