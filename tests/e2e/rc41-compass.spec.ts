import { readFile } from 'node:fs/promises'
import { test, expect, restoreViaUI, readAllState } from './fixtures'
import { rc41Fixture } from '../rc41Fixture'
import { createRc41Map, recordRc41Position } from '../rc41UiHelpers'

test('RC41 compass stays fixed during zoom/pan, allows pointer input underneath, and preserves historical north through v12 restore',async({page},info)=>{
  await restoreViaUI(page,rc41Fixture())
  await page.locator('.trip-row[data-trip-id="1"]').click()
  await createRc41Map(page,'方位ポンド')
  await recordRc41Position(page,'方位ポンド')
  const original=(await readAllState(page)).tripEvents![0]!
  expect(original.fishingPosition.snapshot).not.toHaveProperty('northAngle')
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  const manager=page.getByRole('dialog',{name:'エリアマップ管理',exact:true})
  await manager.getByRole('button',{name:'編集：方位ポンド',exact:true}).click()
  const compass=manager.getByTestId('map-compass'),needle=compass.getByTestId('compass-needle')
  await expect(compass).toHaveAttribute('data-configured','false')
  await expect(compass).toHaveAttribute('data-north-angle','0')
  await expect(manager.getByLabel('北方向の角度（度）',{exact:true})).toBeDisabled()
  await manager.getByLabel('北方向を設定する（手動）',{exact:true}).check()
  await manager.getByLabel('北方向の角度（度）',{exact:true}).fill('90')
  await expect(compass).toHaveAttribute('data-configured','true')
  await expect(needle).toHaveAttribute('transform','rotate(90 24 24)')
  const svg=manager.getByRole('img',{name:'方位ポンドのエリアマップ',exact:true})
  const offset=async()=>{const a=(await svg.boundingBox())!,b=(await compass.boundingBox())!;return {top:b.y-a.y,right:a.x+a.width-b.x-b.width}}
  const fixed=await offset()
  await manager.getByRole('button',{name:'マップを拡大',exact:true}).click()
  await manager.getByRole('button',{name:'マップを右へ',exact:true}).click()
  await expect(svg).not.toHaveAttribute('viewBox','0 0 1 1')
  expect(await offset()).toEqual(fixed)
  await expect(needle).toHaveAttribute('transform','rotate(90 24 24)')
  expect(await compass.evaluate(el=>getComputedStyle(el).pointerEvents)).toBe('none')
  await manager.getByRole('button',{name:'全体表示',exact:true}).click()
  await manager.getByRole('button',{name:'インレット追加',exact:true}).click()
  await svg.scrollIntoViewIfNeeded()
  const box=(await compass.boundingBox())!
  await page.mouse.click(box.x+box.width/2,box.y+box.height/2)
  await expect(svg.locator('[data-feature-id]')).toHaveCount(3)
  await manager.screenshot({path:info.outputPath('rc41-compass-editor.png')})
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：方位ポンド',exact:true})).toBeVisible()
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  await recordRc41Position(page,'方位ポンド')
  const newer=(await readAllState(page)).tripEvents!.at(-1)!
  expect(newer.fishingPosition.snapshot.northAngle).toBe(90)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  await manager.getByRole('button',{name:'編集：方位ポンド',exact:true}).click()
  await manager.getByLabel('北方向の角度（度）',{exact:true}).fill('270')
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：方位ポンド',exact:true})).toBeVisible()
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  await page.getByRole('button',{name:'釣り座を記録',exact:true}).click()
  const editor=page.getByRole('dialog',{name:'イベント追加',exact:true})
  await expect(editor.getByLabel('北方向の角度（度）',{exact:true})).toHaveCount(0)
  await expect(editor.getByTestId('map-compass')).toHaveAttribute('data-north-angle','90')
  await editor.getByRole('button',{name:'キャンセル',exact:true}).click()
  await page.getByRole('button',{name:'← ホーム',exact:true}).click()
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'📦 データをバックアップ',exact:true}).click()])
  const path=info.outputPath('rc41-north-v12.json');await download.saveAs(path)
  const backup=JSON.parse(await readFile(path,'utf8'))
  expect(backup.version).toBe(12);expect(backup.data.areaMaps[0].northAngle).toBe(270)
  await restoreViaUI(page,backup)
  const restored=(await readAllState(page)).tripEvents!
  expect(restored[0]!.fishingPosition).toEqual(original.fishingPosition)
  expect(restored.at(-1)!.fishingPosition).toEqual(newer.fishingPosition)
  await page.locator('.trip-row[data-trip-id="1"]').click()
  const entries=page.locator('.event-entry')
  await entries.first().getByText('釣り座の詳細',{exact:true}).click()
  await expect(entries.first().getByTestId('map-compass')).toHaveAttribute('data-north-angle','90')
  await entries.last().getByText('釣り座の詳細',{exact:true}).click()
  await expect(entries.last().getByTestId('map-compass')).toHaveAttribute('data-configured','false')
  await page.getByRole('button',{name:'← ホーム',exact:true}).click()
  await page.getByRole('button',{name:'新しい釣行を開始'}).click()
  await page.getByLabel('管理釣り場',{exact:true}).selectOption('user:rc41-f')
  await page.getByRole('button',{name:'🎣 釣行開始',exact:true}).click()
  await recordRc41Position(page,'方位ポンド')
  const nextTrip=(await readAllState(page)).tripEvents!.at(-1)!
  expect(nextTrip.tripId).not.toBe(1)
  expect(nextTrip.fishingPosition.snapshot.northAngle).toBe(270)
})

test('RC41 explicit zero and unset remain distinct, invalid angles do not save, and cancel keeps persisted north',async({page})=>{
  await restoreViaUI(page,rc41Fixture());await page.locator('.trip-row[data-trip-id="1"]').click()
  await createRc41Map(page,'ゼロ度ポンド','P01',false)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  const manager=page.getByRole('dialog',{name:'エリアマップ管理',exact:true})
  await manager.getByRole('button',{name:'編集：ゼロ度ポンド',exact:true}).click()
  await manager.getByLabel('北方向を設定する（手動）',{exact:true}).check()
  await manager.getByLabel('北方向の角度（度）',{exact:true}).fill('360')
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('alert')).toContainText('0〜359度')
  await manager.getByLabel('北方向の角度（度）',{exact:true}).fill('0')
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：ゼロ度ポンド',exact:true})).toBeVisible()
  await manager.getByRole('button',{name:'編集：ゼロ度ポンド',exact:true}).click()
  await expect(manager.getByTestId('map-compass')).toHaveAttribute('data-configured','true')
  await expect(manager.getByTestId('map-compass')).toHaveAttribute('data-north-angle','0')
  await manager.getByLabel('北方向を設定する（手動）',{exact:true}).uncheck()
  await manager.getByRole('button',{name:'キャンセル',exact:true}).click()
  await manager.getByRole('button',{name:'編集：ゼロ度ポンド',exact:true}).click()
  await expect(manager.getByLabel('北方向を設定する（手動）',{exact:true})).toBeChecked()
  await manager.getByLabel('北方向を設定する（手動）',{exact:true}).uncheck()
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：ゼロ度ポンド',exact:true})).toBeVisible()
  await expect(manager.getByTestId('map-compass')).toHaveAttribute('data-configured','false')
})
