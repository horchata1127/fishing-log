import { checkMaster, applyMaster, masterHome } from '../masterUiHelpers'
import { assertPack } from './masterCatalogRegression'
import { rc33Catalog } from '../../src/data/rc33Catalog'
import { test, expect, catalogFixture, readState, restoreViaUI, startTrip, saveCatch } from './fixtures'

test('RC33 preview/cancel, purchases, repeat, dictionary reverse lookup and catch SVG', async ({ page }) => {
  await restoreViaUI(page, catalogFixture())
  const before = await readState(page)
  await checkMaster(page)
  await expect(page.getByRole('region', { name: '統一マスターの差分プレビュー', exact: true })).toContainText('所有オプション：OFF')
  expect(await readState(page)).toEqual(before)
  await page.getByRole('button', { name: '更新を取り消す', exact: true }).click()
  expect(await readState(page)).toEqual(before)
  await checkMaster(page, true); await applyMaster(page)
  const saved = await readState(page)
  assertPack(saved, rc33Catalog, before)
  expect(saved.myLures).toHaveLength(14)
  expect(saved.myLures.slice(0, 3)).toEqual(before.myLures)
  await checkMaster(page, true); const result = await applyMaster(page)
  for (const row of await result.locator('tbody tr').all()) expect(await row.locator('td').first().textContent()).toBe('0')
  expect(await readState(page)).toEqual(saved)
  await masterHome(page); await page.reload()
  expect(await readState(page)).toEqual(saved)
  const red = saved.lureVariants.find(v => v.colorName === '04 クリアーレッド')!
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  await dictionary.getByLabel('辞書メーカー').selectOption('SMITH')
  await dictionary.getByLabel('所有ルアーのみ').check()
  await dictionary.getByText('色から検索（0色）', { exact: true }).click()
  await dictionary.getByRole('button', { name: 'レッド', exact: true }).click()
  await expect(dictionary.locator('article[data-variant-id]')).toHaveCount(1)
  await expect(dictionary.locator(`article[data-variant-id="${red.id}"]`).getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  await dictionary.getByRole('button', { name: '辞書を閉じる', exact: true }).click()
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: 'ルアーを選ぶ', exact: false }).click()
  const picker = page.getByRole('dialog', { name: 'ルアーを選択', exact: true })
  await picker.getByRole('button', { name: /くるん タイプ1.*04 クリアーレッド/ }).click()
  await saveCatch(page)
  const history = page.getByRole('region', { name: '釣果履歴', exact: true })
  await expect(history.getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  const recorded = (await readState(page)).catches[0]!
  expect(recorded.lureVariantId).toBe(red.id)
  expect(recorded.visualColorSnapshot.appearance.regions.front.colors).toEqual(['red'])
  expect((await readState(page)).myLures).toEqual(saved.myLures)
})
