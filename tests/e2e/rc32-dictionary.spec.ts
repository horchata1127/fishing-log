import { readFile } from 'node:fs/promises'
import { test, expect, catalogFixture, readState, restoreViaUI, startTrip, saveCatch } from './fixtures'

test('代表配色を編集し、メーカー・モデル・所有で色逆引きして公式候補から再利用する', async ({ page }) => {
  const fixture = catalogFixture(); fixture.data.myLures[0]!.ownershipStatus = 'owned'
  await restoreViaUI(page, fixture)
  const before = await readState(page)
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  const red = dictionary.locator('article[data-variant-id="40"]'), blue = dictionary.locator('article[data-variant-id="41"]')
  await red.getByRole('button', { name: '代表配色を編集', exact: true }).click()
  const editor = dictionary.getByRole('region', { name: 'ビジュアルカラー入力' })
  await editor.getByRole('button', { name: 'レッド', exact: true }).click()
  await dictionary.getByRole('button', { name: '代表配色を保存', exact: true }).click()
  await expect(red.getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  await blue.getByRole('button', { name: '代表配色を編集', exact: true }).click()
  await editor.getByRole('button', { name: 'ブルー', exact: true }).click()
  await dictionary.getByRole('button', { name: '代表配色を保存', exact: true }).click()
  await expect(blue.getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  expect(await readState(page)).toEqual(before)
  await dictionary.getByText('色から検索（0色）', { exact: true }).click()
  await dictionary.getByRole('button', { name: 'レッド', exact: true }).click()
  await expect(dictionary.locator('article')).toHaveCount(1)
  await expect(red).toBeVisible()
  await dictionary.getByLabel('辞書メーカー').selectOption('E2Eメーカー')
  await dictionary.getByLabel('辞書モデル').selectOption('30')
  await dictionary.getByLabel('所有ルアーのみ').check()
  await expect(red).toBeVisible()
  await dictionary.getByRole('button', { name: 'レッド', exact: true }).click()
  await dictionary.getByRole('button', { name: 'ブルー', exact: true }).click()
  await expect(dictionary.locator('article')).toHaveCount(0)
  await dictionary.getByLabel('所有ルアーのみ').uncheck()
  await expect(blue).toBeVisible()
  await dictionary.getByRole('button', { name: '辞書を閉じる', exact: true }).click()
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: 'ルアーを選ぶ', exact: false }).click()
  const picker = page.getByRole('dialog', { name: 'ルアーを選択', exact: true })
  await expect(picker.getByRole('img', { name: '配色プレビュー' })).toHaveCount(1)
  await picker.getByRole('button', { name: /E2Eスプーン.*赤/ }).click()
  await expect(modal.getByRole('region', { name: 'ビジュアルカラー入力' }).getByRole('button', { name: 'レッド', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await saveCatch(page)
  expect((await readState(page)).catches[0]!.visualColorSnapshot.appearance.regions.front.colors).toEqual(['red'])
  expect((await readState(page)).myLures).toEqual(before.myLures)
})

test('仮配色を後から紐付け、過去配色と所有を保持し、辞書編集後も履歴とv8を保持する', async ({ page }, info) => {
  await restoreViaUI(page, catalogFixture())
  const originalCatalog = await readState(page)
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  let modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('region', { name: 'ビジュアルカラー入力' }).getByRole('button', { name: 'ゴールド', exact: true }).click()
  await saveCatch(page)
  const provisional = (await readState(page)).catches[0]!
  const history = page.getByRole('region', { name: '釣果履歴' })
  await history.getByRole('button', { name: '公式カラーへ紐付け', exact: true }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  await dictionary.locator('article[data-variant-id="40"]').getByRole('button', { name: 'この仮配色を紐付け', exact: true }).click()
  await expect(dictionary).not.toBeVisible()
  const linked = (await readState(page)).catches[0]!
  expect(linked.lureVariantId).toBe(40); expect(linked).not.toHaveProperty('lureId')
  expect(linked.visualColorSnapshot).toEqual(provisional.visualColorSnapshot)
  expect((await readState(page)).myLures).toEqual(originalCatalog.myLures)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await modal.getByRole('button', { name: /前回と同じ/ }).click()
  await expect(modal).not.toBeVisible()
  expect((await readState(page)).myLures).toEqual(originalCatalog.myLures)
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  const row = dictionary.locator('article[data-variant-id="40"]')
  await row.getByRole('button', { name: '代表配色を編集', exact: true }).click()
  const editor = dictionary.getByRole('region', { name: 'ビジュアルカラー入力' })
  await editor.getByRole('button', { name: 'ゴールド', exact: true }).click()
  await editor.getByRole('button', { name: 'ブルー', exact: true }).click()
  await dictionary.getByRole('button', { name: '代表配色を保存', exact: true }).click()
  await expect(row.getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  expect((await readState(page)).catches.map(c => c.visualColorSnapshot)).toEqual([provisional.visualColorSnapshot, provisional.visualColorSnapshot])
  await dictionary.getByRole('button', { name: '辞書を閉じる', exact: true }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('synthetic-rc32-dictionary-v8.json'); await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8'))
  expect(backup.version).toBe(8)
  expect(backup.data.lureVisualProfiles[0].appearance.regions.whole.colors).toEqual(['blue'])
  expect(backup.data.temporaryLureColors[0].linkedVariantId).toBe(40)
  const before = await readState(page); await restoreViaUI(page, backup); expect(await readState(page)).toEqual(before)
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: '色から探す・代表配色を編集', exact: true }).click()
  await dictionary.locator('article[data-variant-id="40"]').getByRole('button', { name: 'この公式カラーを選ぶ', exact: true }).click()
  await expect(modal.getByRole('region', { name: 'ビジュアルカラー入力' }).getByRole('button', { name: 'ブルー', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await modal.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect((await readState(page)).myLures).toEqual(originalCatalog.myLures)
})

test('保存済み仮カラーマスターから明示的に紐付けても所有・釣果を変更しない', async ({ page }) => {
  const fixture = catalogFixture()
  const backup = { ...fixture, version: 8, data: { ...fixture.data, fishSpecies: [], facilities: [], zones: [], appMetadata: [],
    tripWeatherLocations: [], tripWeatherHours: [], tripWeatherRequests: [], lureVisualProfiles: [], temporaryLureColors: [{
      id: '00000000-0000-4000-8000-000000000001', name: '合成の仮カラー',
      appearance: { version: 1, paletteVersion: 1, layout: 'generic', regions: { whole: { colors: ['green'], attributes: [] } } },
      origin: 'user', userEdited: true, confirmed: true, revision: 1, updatedAt: '2026-10-31T00:00:00.000Z',
    }] } }
  await restoreViaUI(page, backup)
  const before = await readState(page)
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  await dictionary.getByText('保存済みの未紐付け仮カラー（1件）', { exact: true }).click()
  await dictionary.getByRole('button', { name: 'この仮カラーの紐付け先を選ぶ', exact: true }).click()
  await dictionary.locator('article[data-variant-id="40"]').getByRole('button', { name: 'この仮配色を紐付け', exact: true }).click()
  await expect(dictionary).not.toBeVisible()
  expect(await readState(page)).toEqual(before)
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  await expect(dictionary.locator('article[data-variant-id="40"]').getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  await expect(dictionary.getByText('保存済みの未紐付け仮カラー（1件）', { exact: true })).not.toBeVisible()
})
