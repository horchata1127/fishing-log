import { readFile } from 'node:fs/promises'
import { test, expect, catalogFixture, readState, restoreViaUI, startTrip } from './fixtures'

test('管理辞書で推定を確認・取消・取り込みし、検索・手動確認・v8復元後も保持する', async ({ page }, info) => {
  const fixture = catalogFixture()
  fixture.data.lureVariants = [{ id: 40, modelId: 30, colorName: '赤金' }, { id: 41, modelId: 30, colorName: 'クリアピンク' }, { id: 42, modelId: 30, colorName: 'T-4A' }]
  await restoreViaUI(page, fixture)
  const original = await readState(page)
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  await dictionary.getByText('推定配色を一括取り込み（管理）', { exact: true }).click()
  await dictionary.getByRole('button', { name: '推定件数を確認', exact: true }).click()
  const preview = dictionary.getByRole('region', { name: '推定配色の事前確認', exact: true })
  await expect(preview).toContainText('新規追加 2件・既存保持 0件・保護 0件・保留 0件・推定不可 1件')
  expect(await readState(page)).toEqual(original)
  await preview.getByRole('button', { name: '推定取り込みをキャンセル', exact: true }).click()
  await expect(preview).not.toBeVisible()
  await expect(dictionary.locator('article[data-variant-id="40"]').getByRole('img', { name: '配色プレビュー' })).toHaveCount(0)
  await dictionary.getByRole('button', { name: '推定件数を確認', exact: true }).click()
  await preview.getByRole('button', { name: '確認した推定配色を取り込む', exact: true }).click()
  await expect(dictionary.getByText('推定配色を2件追加しました。既存配色・釣果・所有情報は保持しています。', { exact: true })).toBeVisible()
  const row = dictionary.locator('article[data-variant-id="40"]')
  await expect(row.getByRole('img', { name: '配色プレビュー' })).toBeVisible()
  await expect(row).toContainText('名称推定・未確認')
  expect(await readState(page)).toEqual(original)
  await dictionary.getByText('色から検索（0色）', { exact: true }).click()
  await dictionary.getByRole('button', { name: 'レッド', exact: true }).click()
  await expect(dictionary.locator('article[data-variant-id]')).toHaveCount(1)
  await row.getByRole('button', { name: '代表配色を編集', exact: true }).click()
  const editor = dictionary.getByRole('region', { name: 'ビジュアルカラー入力' })
  await expect(editor.getByRole('button', { name: 'レッド', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await dictionary.getByRole('button', { name: '代表配色を保存', exact: true }).click()
  await expect(row).toContainText('手動編集・確認済み')
  await dictionary.getByText('推定配色を一括取り込み（管理）', { exact: true }).click()
  await dictionary.getByRole('button', { name: '推定件数を確認', exact: true }).click()
  await expect(preview).toContainText('新規追加 0件・既存保持 1件・保護 1件・保留 0件・推定不可 1件')
  await expect(preview.getByRole('button', { name: '確認した推定配色を取り込む', exact: true })).toBeDisabled()
  await preview.getByRole('button', { name: '推定取り込みをキャンセル', exact: true }).click()
  await dictionary.getByRole('button', { name: '辞書を閉じる', exact: true }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('synthetic-auto-v8.json'); await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8'))
  expect(backup.version).toBe(8); expect(backup.data.lureVisualProfiles).toHaveLength(2)
  expect(backup.data.lureVisualProfiles.find((p: any) => p.variantId === 41)).toMatchObject({ origin: 'name', confirmed: false, userEdited: false, evidence: { estimatorVersion: 'rc32-name-v1', inputName: 'クリアピンク' } })
  await restoreViaUI(page, backup); expect(await readState(page)).toEqual(original)
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: '色から探す・代表配色を編集', exact: true }).click()
  await expect(dictionary.getByText('推定配色を一括取り込み（管理）', { exact: true })).toHaveCount(0)
  await dictionary.locator('article[data-variant-id="41"]').getByRole('button', { name: 'この公式カラーを選ぶ', exact: true }).click()
  await expect(modal.getByRole('region', { name: 'ビジュアルカラー入力' }).getByRole('button', { name: 'ピンク', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('推定プレビュー後の手動編集を検出し、古いプレビューから追加しない', async ({ page }) => {
  const fixture = catalogFixture(); fixture.data.lureVariants[0]!.colorName = '赤金'
  await restoreViaUI(page, fixture)
  await page.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  await dictionary.getByText('推定配色を一括取り込み（管理）', { exact: true }).click()
  await dictionary.getByRole('button', { name: '推定件数を確認', exact: true }).click()
  await expect(dictionary.getByRole('region', { name: '推定配色の事前確認', exact: true })).toBeVisible()
  const second = await page.context().newPage()
  try {
    await second.goto('/')
    await second.getByRole('button', { name: 'ビジュアルカラー辞書', exact: true }).click()
    const other = second.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
    await other.locator('article[data-variant-id="40"]').getByRole('button', { name: '代表配色を編集', exact: true }).click()
    await other.getByRole('region', { name: 'ビジュアルカラー入力' }).getByRole('button', { name: 'ブルー', exact: true }).click()
    await other.getByRole('button', { name: '代表配色を保存', exact: true }).click()
    await expect(other.locator('article[data-variant-id="40"]')).toContainText('手動編集・確認済み')
    await dictionary.getByRole('button', { name: '確認した推定配色を取り込む', exact: true }).click()
    await expect(dictionary.getByText('カタログまたは配色が変更されました。取り込み前の確認をやり直してください。', { exact: true })).toBeVisible()
    await dictionary.getByRole('button', { name: '推定件数を確認', exact: true }).click()
    await expect(dictionary.getByRole('region', { name: '推定配色の事前確認', exact: true })).toContainText('保護 1件')
  } finally { await second.close() }
})
