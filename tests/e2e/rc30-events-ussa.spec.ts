import { test, expect, readState, restoreViaUI } from './fixtures'
import { rc30Fixture } from '../rc30Fixture'
import { readFile } from 'node:fs/promises'

test('RC30 ended trip event CRUD, mixed timeline, validation, reload and v7 restore', async ({ page }, info) => {
  await restoreViaUI(page, rc30Fixture())
  const before = await readState(page)
  await page.getByRole('button', { name: /白馬八方ニレ池/ }).click()
  await page.getByRole('button', { name: 'イベント追加', exact: true }).click()
  let editor = page.getByRole('dialog', { name: 'イベント追加', exact: true })
  await editor.getByLabel('発生日時（日本時間）').fill('2026-10-24T10:30')
  await editor.getByLabel('対象エリア').selectOption('user:rc30-zone')
  await editor.getByLabel('メモ').fill('イワナ・ロック・レインボー放流予定時刻。現地放流を確認した記録')
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await expect(editor).toHaveCount(0)
  let state = await readState(page)
  const id = state.tripEvents[0]!.id
  expect(state.tripEvents[0]!.occurredAt).toBe('2026-10-24T01:30:00.000Z')
  await page.getByText('釣果・イベントの時系列一覧', { exact: true }).click()
  const list = page.getByRole('list', { name: '釣果・イベントの時系列一覧' })
  await expect(list.getByRole('button')).toHaveText([/放流.*10:30/, /釣果.*10:36/, /バラシ.*11:48/])
  const entry = page.locator('.event-entry')
  await entry.getByRole('button', { name: '編集', exact: true }).click()
  editor = page.getByRole('dialog', { name: 'イベントを編集', exact: true })
  await editor.getByLabel('発生日時（日本時間）').fill('2026-10-23T10:30')
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await expect(editor.getByRole('alert')).toContainText('釣行日')
  expect((await readState(page)).tripEvents[0]!.occurredAt).toBe('2026-10-24T01:30:00.000Z')
  await editor.getByLabel('発生日時（日本時間）').fill('2026-10-24T11:00')
  await editor.getByLabel('イベント種別').selectOption('pellet')
  await editor.getByLabel('メモ').fill('ペレットへ編集')
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await expect(editor).toHaveCount(0)
  expect((await readState(page)).tripEvents.map(e => e.id)).toEqual([id])
  page.once('dialog', d => d.dismiss())
  await entry.getByRole('button', { name: '削除', exact: true }).click()
  expect((await readState(page)).tripEvents).toHaveLength(1)
  page.once('dialog', d => d.accept())
  await entry.getByRole('button', { name: '削除', exact: true }).click()
  await expect(entry).toHaveCount(0)
  await page.getByRole('button', { name: 'イベント追加', exact: true }).click()
  editor = page.getByRole('dialog', { name: 'イベント追加', exact: true })
  await editor.getByLabel('イベント種別').selectOption('pellet')
  await editor.getByLabel('発生日時（日本時間）').fill('2026-10-24T10:30')
  const bounds = await editor.boundingBox()
  expect(bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath('rc30-event-editor.png') })
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await expect(editor).toHaveCount(0)
  state = await readState(page)
  for (const key of Object.keys(before) as (keyof typeof before)[]) if (key !== 'tripEvents') expect(state[key]).toEqual(before[key])
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await page.reload()
  expect(await readState(page)).toEqual(state)
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('rc30-v7.json'); await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8')); expect(backup.version).toBe(7)
  await restoreViaUI(page, backup); expect(await readState(page)).toEqual(state)
})

test('RC30 catalog preview, cancellation, repeat apply, model-specific searchable color picker', async ({ page }) => {
  await restoreViaUI(page, rc30Fixture())
  const before = await readState(page)
  const check = page.getByRole('button', { name: 'RC30 USSAの追加予定を確認', exact: true })
  const preview = page.getByRole('region', { name: 'RC30カタログの事前確認', exact: true })
  await check.click()
  await expect(preview).toContainText('追加 140色・登録済み 0色')
  expect(await readState(page)).toEqual(before)
  await preview.getByRole('button', { name: 'RC30の追加をキャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(before)
  await check.click()
  await preview.getByRole('button', { name: 'RC30の確認済みカタログを追加', exact: true }).click()
  await expect(preview).toHaveCount(0)
  const saved = await readState(page)
  expect(saved.lureVariants).toHaveLength(141)
  expect(saved.lureVariants.find(v => v.id === 386)).toEqual(before.lureVariants[0])
  expect(saved.myLures).toEqual(before.myLures); expect(saved.catches).toEqual(before.catches)
  await check.click()
  await expect(preview).toContainText('追加 0色・登録済み 140色')
  await preview.getByRole('button', { name: 'RC30の追加をキャンセル', exact: true }).click()
  await page.getByRole('button', { name: /マイルアー/ }).first().click()
  await page.getByRole('group', { name: 'メーカーの候補', exact: true }).getByRole('button', { name: 'RODIO CRAFT', exact: true }).click()
  await page.getByRole('group', { name: 'シリーズの候補', exact: true }).getByRole('button', { name: 'USSA', exact: true }).click()
  const models = page.getByRole('group', { name: 'モデルの候補', exact: true })
  await expect(models.getByRole('button')).toHaveCount(5)
  await models.getByRole('button', { name: 'Fat USSA Jr. XS', exact: true }).click()
  const colors = page.getByRole('group', { name: 'カラーの候補', exact: true })
  await expect(colors.getByRole('button')).toHaveCount(21)
  await page.getByLabel('カラーを検索', { exact: true }).fill('クリアー')
  await expect(colors.getByRole('button')).toHaveCount(3)
  expect((await readState(page)).myLures).toEqual(before.myLures)
})
