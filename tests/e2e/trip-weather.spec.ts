import { test, expect, readCompleteState, restoreViaUI } from './fixtures'
import { weatherResponse, weatherScenario, weatherStoreNames, weatherTripId, weatherTripName } from '../weatherFixture'

const archive = 'https://archive-api.open-meteo.com/v1/archive**'
test('Iwana 2026-10-17 real archive replay: manual location, JST mismatch, refresh, failure and v7 backup protect old records', async ({ page }, info) => {
  await page.clock.install({ time: new Date('2026-10-23T00:00:00Z') })
  await restoreViaUI(page, weatherScenario())
  const before = await readCompleteState(page)
  let calls = 0, fail = false
  await page.route(archive, async route => {
    calls++; const q = new URL(route.request().url()).searchParams
    expect(q.get('start_date')).toBe('2026-10-17'); expect(q.get('end_date')).toBe('2026-10-17')
    expect(q.get('hourly')).toContain('surface_pressure'); expect(q.get('timeformat')).toBe('unixtime')
    await route.fulfill({ status: fail ? 503 : 200, contentType: 'application/json', body: JSON.stringify(fail ? {} : weatherResponse) })
  })
  await page.getByRole('button', { name: new RegExp(weatherTripName.replace(/[（）]/g, '.')) }).click()
  const panel = page.getByRole('region', { name: '気象データ', exact: true })
  await panel.locator('summary').click()
  await expect(panel.getByText(/保存済み日付 2026-10-16/)).toBeVisible()
  await expect(panel.getByLabel('緯度', { exact: true })).toHaveValue(''); expect(calls).toBe(0)
  await panel.getByLabel('緯度', { exact: true }).fill('91'); await panel.getByLabel('経度', { exact: true }).fill('139.194')
  await panel.getByRole('button', { name: '地点を保存', exact: true }).click(); await expect(panel.getByRole('alert')).toContainText('緯度')
  await panel.getByLabel('緯度', { exact: true }).fill('36.611'); await panel.getByRole('button', { name: '地点を保存', exact: true }).click()
  await expect(panel.getByRole('status').filter({ hasText: '手動地点を保存' })).toBeVisible(); expect(calls).toBe(0)
  await panel.getByRole('button', { name: '過去の気象データを取得', exact: true }).click()
  await expect(panel.locator('tbody tr')).toHaveCount(24)
  const first = panel.locator('tbody tr').first()
  await expect(first).toContainText('2026/10/17 00:00'); await expect(first.locator('td').nth(4)).toHaveText(String(weatherResponse.hourly.surface_pressure[0]))
  await expect(panel.getByText(/モデルのグリッド地点/)).toContainText(String(weatherResponse.longitude))
  await expect(panel.getByRole('link', { name: 'Weather data by Open-Meteo.com' })).toBeVisible()
  await expect(panel.getByText(/釣り場現地で測定された値ではありません/)).toBeVisible()
  await panel.getByRole('button', { name: '過去の気象データを再取得', exact: true }).click()
  await expect.poll(() => calls).toBe(2); await expect(panel.getByRole('status').filter({ hasText: '気象データを保存しました' })).toBeVisible()
  const saved = await page.evaluate(async () => { const path = '/fishing-log/src/db/database.ts'; const { db } = await import(path); return JSON.parse(JSON.stringify(await db.tripWeatherHours.toArray())) })
  expect(saved).toHaveLength(24); expect(new Set(saved.map((r: any) => `${r.tripId}:${r.timestamp}`)).size).toBe(24)
  expect(await readCompleteState(page)).toEqual(before)
  expect(before.catches.filter(c => c.tripId === weatherTripId)).toHaveLength(7)
  expect(before.tripEvents.filter(e => e.tripId === weatherTripId)).toHaveLength(0)
  fail = true; await panel.getByRole('button', { name: '過去の気象データを再取得', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('503'); await expect(panel.locator('tbody tr')).toHaveCount(24)
  await expect.poll(async () => page.evaluate(async () => { const path = '/fishing-log/src/db/database.ts'; return JSON.parse(JSON.stringify(await (await import(path)).db.tripWeatherHours.toArray())) })).toEqual(saved)
  await page.screenshot({ path: info.outputPath('weather-ui.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('weather-v7.json'); await download.saveAs(path)
  const backup = JSON.parse(await (await import('node:fs/promises')).readFile(path, 'utf8'))
  expect(backup.version).toBe(7); expect(Object.keys(backup.data)).toHaveLength(19)
  for (const name of weatherStoreNames) expect(backup.data[name].length).toBeGreaterThan(0)
  await restoreViaUI(page, backup); expect(await readCompleteState(page)).toEqual(before)
  await page.reload(); await page.getByRole('button', { name: new RegExp(weatherTripName.replace(/[（）]/g, '.')) }).click(); await panel.locator('summary').click()
  await expect(panel.locator('tbody tr')).toHaveCount(24); expect(calls).toBe(3)
})

test('today waits without network; partial archive preserves explicit missing values and permits manual retry', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-17T10:00:00Z') }); await restoreViaUI(page, weatherScenario())
  let calls = 0
  const partial = structuredClone(weatherResponse); partial.hourly.temperature_2m[0] = null
  await page.route(archive, async route => { calls++; await route.fulfill({ contentType: 'application/json', body: JSON.stringify(partial) }) })
  await page.getByRole('button', { name: new RegExp(weatherTripName.replace(/[（）]/g, '.')) }).click()
  const panel = page.getByRole('region', { name: '気象データ', exact: true }); await panel.locator('summary').click()
  await panel.getByLabel('緯度', { exact: true }).fill('36.611'); await panel.getByLabel('経度', { exact: true }).fill('139.194')
  await panel.getByRole('button', { name: '地点を保存', exact: true }).click()
  await panel.getByRole('button', { name: '過去の気象データを取得', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('提供されてから再試行'); expect(calls).toBe(0)
  await page.clock.setSystemTime(new Date('2026-10-23T00:00:00Z'))
  await panel.getByRole('button', { name: '過去の気象データを取得', exact: true }).click()
  await expect(panel.locator('tbody tr').first().locator('td').first()).toHaveText('—')
  await expect(panel.getByRole('status').filter({ hasText: '一部欠損' })).toBeVisible(); expect(calls).toBe(1)
})
