import { readFile } from 'node:fs/promises'
import { test, expect, readState, restoreViaUI } from './fixtures'
import { rc20Fixture } from '../rc20Fixture'

test('RC21 preview, CSV, cancellation, 282 additions, historical preservation, repeat and backup restoration', async ({ page }, info) => {
  await restoreViaUI(page, rc20Fixture())
  await page.getByRole('button', { name: 'RC20の追加予定を確認', exact: true }).click()
  await page.getByRole('button', { name: 'RC20の確認済みカラーを追加', exact: true }).click()
  await expect(page.getByRole('region', { name: 'RC20カタログの事前確認', exact: true })).not.toBeVisible()
  const before = await readState(page)
  const check = page.getByRole('button', { name: 'RC21の追加予定を確認', exact: true })
  const preview = page.getByRole('region', { name: 'RC21カタログの事前確認', exact: true })
  await check.click()
  await expect(preview).toContainText('追加 282色・登録済み 0色・保留 0色')
  await expect(preview).toContainText('新しいモデル 18件・シリーズ 8件')
  await preview.getByText('モデル別の追加予定', { exact: true }).click()
  await expect(preview).toContainText('フォルテ 0.6g：追加 21色')
  await expect(preview).toContainText('フォルテ 0.9g：追加 25色')
  expect(await readState(page)).toEqual(before)
  const download = page.waitForEvent('download')
  await preview.getByRole('button', { name: '照合結果をCSVで保存', exact: true }).click()
  const path = info.outputPath('rc21-device-diff.csv')
  await (await download).saveAs(path)
  const csv = await readFile(path, 'utf8')
  expect(csv.trim().split('\n')).toHaveLength(283)
  expect(csv).toContain('manufacturer_id,series_id,model_id,hold_reason')
  expect(csv).toContain('https://velvetarts.co.jp/')
  await preview.getByRole('button', { name: 'RC21の追加をキャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(before)
  await check.click()
  await preview.getByRole('button', { name: 'RC21の確認済みカラーを追加', exact: true }).click()
  await expect(preview).not.toBeVisible()
  const saved = await readState(page)
  for (const [table, rows] of Object.entries(before)) {
    const records = saved[table as keyof typeof saved]
    for (const row of rows) expect(records.find(r => (r.id ?? r.fish_id) === (row.id ?? row.fish_id))).toEqual(row)
    if (!['lureSeries', 'lureModels', 'lureVariants'].includes(table)) expect(records).toEqual(rows)
  }
  expect(saved.lureVariants.length - before.lureVariants.length).toBe(282)
  expect(saved.lureModels.length - before.lureModels.length).toBe(18)
  expect(saved.lureSeries.length - before.lureSeries.length).toBe(8)
  await check.click()
  await expect(preview).toContainText('追加 0色・登録済み 282色・保留 0色')
  await expect(preview.getByRole('button', { name: 'RC21の確認済みカラーを追加', exact: true })).toBeDisabled()
  await preview.getByRole('button', { name: 'RC21の追加をキャンセル', exact: true }).click()
  await page.reload()
  expect(await readState(page)).toEqual(saved)
  const backupDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()
  const backupPath = info.outputPath('rc21-backup.json')
  await (await backupDownload).saveAs(backupPath)
  const backup = JSON.parse(await readFile(backupPath, 'utf8'))
  for (const [table, rows] of Object.entries(saved)) {
    if (table in backup.data) expect(backup.data[table]).toEqual(rows)
    else expect(rows).toEqual([])
  }
  await restoreViaUI(page, backup)
  expect(await readState(page)).toEqual(saved)
})
