import { test, expect, catalogFixture, readState, restoreViaUI, startTrip, selectCatalog, saveCatch } from './fixtures'

test('終了済み釣行の編集・キャンセル・再読込でIDと件数を保持する', async ({ page }) => {
  await restoreViaUI(page, catalogFixture())
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await selectCatalog(page)
  await saveCatch(page)
  const original = await readState(page)
  const history = page.getByRole('region', { name: '釣果履歴' })
  await history.getByRole('button', { name: '編集', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await modal.getByLabel('メモ（任意）').fill('キャンセルする変更')
  await modal.getByRole('button', { name: 'キャンセル', exact: true }).click()
  expect(await readState(page)).toEqual(original)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: /釣行を終了/ }).click()
  await page.getByRole('button', { name: /E2Eニレ池/ }).click()
  await history.getByRole('button', { name: '編集', exact: true }).click()
  await modal.getByLabel('釣果日時', { exact: true }).fill('2026-10-11T06:12')
  await modal.getByRole('button', { name: '手入力する', exact: false }).click()
  await modal.getByLabel('ルアー名', { exact: true }).fill('HUNT GRANDE 1.3g')
  await modal.getByLabel('カラー', { exact: true }).fill('シルバー')
  await modal.getByRole('combobox', { name: '魚種を選択', exact: true }).selectOption('RC19-F001')
  await modal.getByLabel('メモ（任意）').fill('実釣訂正')
  await modal.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(modal).not.toBeVisible()
  const edited = await readState(page)
  expect(edited.catches).toHaveLength(original.catches.length)
  expect(edited.catches[0]).toMatchObject({ id: original.catches[0]!.id, tripId: original.catches[0]!.tripId,
    lureName: 'HUNT GRANDE 1.3g', lureColor: 'シルバー', fishSpecies: 'カワムツ', memo: '実釣訂正' })
  expect(edited.catches[0]).not.toHaveProperty('lureId')
  expect(edited.catches[0]).not.toHaveProperty('lureVariantId')
  await page.reload()
  expect(await readState(page)).toEqual(edited)
})

test('RC19カラー追加は所有と釣果を変更せず、カタログ選択から保存できる', async ({ page }) => {
  await restoreViaUI(page, catalogFixture())
  const before = await readState(page)
  const add = page.getByRole('button', { name: 'RC19のHUNT GRANDE 1.3g・2色を追加', exact: true })
  await add.click()
  await expect(page.getByRole('status')).toContainText('5件追加')
  const added = await readState(page)
  expect(added.myLures).toEqual(before.myLures)
  expect(added.catches).toEqual(before.catches)
  await add.click()
  await expect(page.getByRole('status')).toContainText('0件追加')
  expect(await readState(page)).toEqual(added)
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: 'ルアーを選ぶ' }).click()
  const picker = page.getByRole('dialog', { name: 'ルアーを選択', exact: true })
  await picker.getByRole('button', { name: 'カタログ', exact: true }).click()
  const model = added.lureModels.find(row => row.name === 'HUNT GRANDE 1.3g')!
  await picker.getByLabel('モデルを選んでからカラーを選択').selectOption(String(model.id))
  await picker.getByRole('button', { name: /T-18 黄茶次郎/ }).click()
  await saveCatch(page)
  const saved = await readState(page)
  expect(saved.catches[0]).toMatchObject({ lureName: 'HUNT GRANDE 1.3g', lureColor: 'T-18 黄茶次郎（KICYAJIRO）' })
  expect(saved.myLures.length).toBe(before.myLures.length + 1)
})
