import { readFile } from 'node:fs/promises'
import { test, expect, readState, restoreViaUI } from './fixtures'
import { rc28Fixture } from '../rc28Fixture'
import { rc28Catalog } from '../../src/data/rc28Catalog'

const colors = rc28Catalog.reduce((n,t)=>n+t.colors.length,0)
test('RC28 preview, cancellation, apply, all model/color pickers, offline reload and v7 backup round trip', async ({page,context},info)=>{
  await restoreViaUI(page,rc28Fixture())
  const before=await readState(page)
  const check=page.getByRole('button',{name:'RC28の追加予定を確認',exact:true})
  const preview=page.getByRole('region',{name:'RC28カタログの事前確認',exact:true})
  await check.click()
  await expect(preview).toContainText(`追加 ${colors}色・登録済み 0色`)
  await expect(preview).toContainText('新しいモデル 20件・シリーズ 5件')
  expect(await readState(page)).toEqual(before)
  const download=page.waitForEvent('download')
  await preview.getByRole('button',{name:'照合結果をCSVで保存',exact:true}).click()
  const csvPath=info.outputPath('rc28-diff.csv')
  await (await download).saveAs(csvPath)
  expect((await readFile(csvPath,'utf8')).trim().split('\n')).toHaveLength(colors+1)
  await preview.getByRole('button',{name:'RC28の追加をキャンセル',exact:true}).click()
  expect(await readState(page)).toEqual(before)
  await check.click()
  await preview.getByRole('button',{name:'RC28の確認済みカタログを追加',exact:true}).click()
  await expect(preview).not.toBeVisible()
  const saved=await readState(page)
  expect(saved.lureVariants.length-before.lureVariants.length).toBe(colors)
  for(const [table,rows] of Object.entries(before)){
    for(const row of rows) expect(saved[table as keyof typeof saved].find(r=>r.id===row.id)).toEqual(row)
    if(!['lureSeries','lureModels','lureVariants'].includes(table)) expect(saved[table as keyof typeof saved]).toEqual(rows)
  }
  await check.click()
  await expect(preview).toContainText(`追加 0色・登録済み ${colors}色`)
  await expect(preview.getByRole('button',{name:'RC28の確認済みカタログを追加',exact:true})).toBeDisabled()
  await preview.getByRole('button',{name:'RC28の追加をキャンセル',exact:true}).click()
  await page.getByRole('button',{name:'🎣 マイルアー',exact:true}).click()
  for(const target of rc28Catalog){
    await page.getByRole('button',{name:/^メーカー/}).first().click()
    const choice = (value: string) => new RegExp('^'+value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'(?: 選択中)?$')
    await page.getByRole('group',{name:'メーカーの候補',exact:true}).getByRole('button',{name:choice(target.manufacturer)}).click()
    await page.getByRole('group',{name:'シリーズの候補',exact:true}).getByRole('button',{name:choice(target.series)}).click()
    await page.getByRole('group',{name:'モデルの候補',exact:true}).getByRole('button',{name:choice(target.model)}).click()
    const candidates=page.getByRole('group',{name:'カラーの候補',exact:true})
    await expect(candidates.getByRole('button')).toHaveCount(target.colors.length)
    await candidates.getByRole('button',{name:target.colors[0]!.label,exact:true}).click()
  }
  expect((await readState(page)).myLures).toEqual(saved.myLures)
  await page.getByRole('button',{name:'← 戻る',exact:true}).click()
  await context.setOffline(true)
  // Catalog selection needs no network after the app has loaded.
  await check.click()
  await expect(preview).toContainText(`登録済み ${colors}色`)
  await preview.getByRole('button',{name:'RC28の追加をキャンセル',exact:true}).click()
  await context.setOffline(false)
  await page.reload()
  expect(await readState(page)).toEqual(saved)
  const backupDownload=page.waitForEvent('download')
  await page.getByRole('button',{name:'📦 データをバックアップ',exact:true}).click()
  const path=info.outputPath('synthetic-rc28-backup.json')
  await (await backupDownload).saveAs(path)
  const backup=JSON.parse(await readFile(path,'utf8'))
  expect(backup.version).toBe(7)
  expect(backup.data.tripWeatherLocations).toEqual(rc28Fixture().data.tripWeatherLocations)
  await restoreViaUI(page,backup)
  expect(await readState(page)).toEqual(saved)
})

test('RC28 two-tab stale confirmation commits once',async({page,context})=>{
  await restoreViaUI(page,rc28Fixture())
  const other=await context.newPage()
  await other.goto('/fishing-log/')
  for(const p of [page,other]) await p.getByRole('button',{name:'RC28の追加予定を確認',exact:true}).click()
  await Promise.all([page,other].map(p=>p.getByRole('button',{name:'RC28の確認済みカタログを追加',exact:true}).click()))
  await expect.poll(async()=>(await readState(page)).lureVariants.length).toBe(colors+1)
  await expect.poll(async()=>(await page.getByRole('status').allTextContents()).join(' ')+(await other.getByRole('status').allTextContents()).join(' ')).toContain('もう一度事前確認')
})
