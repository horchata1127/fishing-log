import { test, expect, restoreViaUI } from './fixtures'
import { facilityLinkScenario } from '../facilityLinkFixture'
import { timelineScenario, timelineState } from '../timelineFixture'
import { weatherTripName } from '../weatherFixture'

test('RC27 legacy seven-catch trip: explicit searched facility link, cancellation, area edit, and weather protection', async ({ page },info) => {
  await restoreViaUI(page,facilityLinkScenario())
  const before = await timelineState(page)
  await page.getByRole('button',{ name:/^日本イワナセンター 2026/ }).click()
  await page.getByRole('button',{ name:'施設を設定・変更',exact:true }).click()
  const dialog = page.getByRole('dialog',{ name:'釣り場・施設を編集',exact:true })
  await expect(dialog.getByLabel('紐付ける正式施設')).toHaveValue('')
  await dialog.getByLabel('正式施設を検索').fill('日本イワナ')
  await dialog.getByLabel('紐付ける正式施設').selectOption('official:nihon-iwana-center')
  expect(await timelineState(page)).toEqual(before)
  await dialog.getByRole('button',{ name:'キャンセル',exact:true }).click(); expect(await timelineState(page)).toEqual(before)
  await page.getByRole('button',{ name:'施設を設定・変更',exact:true }).click()
  await dialog.getByLabel('紐付ける正式施設').selectOption('official:nihon-iwana-center')
  await dialog.getByRole('button',{ name:'施設を保存する',exact:true }).click(); await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('region',{ name:'釣り場・施設',exact:true })).toContainText('official:nihon-iwana-center')
  const linked = await timelineState(page)
  for (const key of Object.keys(before)) if (key !== 'trips') expect(linked[key]).toEqual(before[key])
  expect(linked.trips!.find(t => t.id === 95000)).toEqual({ ...before.trips!.find(t => t.id === 95000),facilityId:'official:nihon-iwana-center' })
  const graph = page.getByRole('region',{ name:'統合タイムライン',exact:true })
  await expect(graph.locator('.catch-summary')).toContainText('総釣果：7匹'); await expect(graph.locator('.catch-summary')).toContainText('0.75匹/時')
  await page.getByRole('region',{ name:'釣果履歴',exact:true }).getByRole('button',{ name:'編集',exact:true }).first().click()
  const catchDialog = page.getByRole('dialog',{ name:'釣果を編集',exact:true }), area = catchDialog.getByLabel('釣り場内のエリア',{exact:true})
  await expect(area.locator('option')).toHaveCount(10)
  await area.selectOption('official:nihon-iwana-center:pond-9')
  await area.scrollIntoViewIfNeeded(); await catchDialog.screenshot({path:info.outputPath('linked-area-mobile.png')})
  await catchDialog.getByRole('button',{ name:'保存する',exact:true }).click(); await expect(catchDialog).toHaveCount(0)
  await graph.getByLabel('釣果・バラシのエリア').selectOption('id:official:nihon-iwana-center:pond-9')
  await graph.getByLabel('エリア未設定も含める').uncheck()
  await expect(graph.locator('.catch-summary')).toContainText('表示中：1匹／全体：7匹')
  expect(await graph.locator('.hour-bar').evaluateAll(nodes => nodes.reduce((n,e) => n+Number((e as HTMLElement).dataset.count),0))).toBe(1)
  const edited = await timelineState(page)
  expect(edited.catches!.find(c => c.id === 95006).memo).toBe('ゼロ号池')
  for (const name of ['tripWeatherHours','tripWeatherRequests','tripWeatherLocations']) expect(edited[name]).toEqual(before[name])
  await page.getByRole('button',{ name:'← ホーム',exact:true }).click(); await page.reload()
  expect((await timelineState(page)).trips).toEqual(linked.trips)
})

test('RC27 facility change warns, keeps old catch zones distinct, preserves backup references and rolls back failure', async ({ page }) => {
  await restoreViaUI(page,timelineScenario())
  const before = await timelineState(page)
  const target = before.facilities!.find(f => f.origin === 'official' && f.id !== 'official:nihon-iwana-center')!
  await page.getByRole('button',{ name:new RegExp(weatherTripName.replace(/[（）]/g,'.')) }).click()
  await page.getByRole('button',{ name:'施設を設定・変更',exact:true }).click()
  const dialog = page.getByRole('dialog',{ name:'釣り場・施設を編集',exact:true })
  await dialog.getByLabel('紐付ける正式施設').selectOption(target.id)
  await expect(dialog.getByText(/旧施設・所属未確認のエリアが残る記録：7件/)).toBeVisible()
  await expect(dialog.getByRole('button',{ name:'施設を保存する',exact:true })).toBeDisabled()
  await dialog.getByLabel('旧エリアを保持し、必要な現在エリアの解除を確認しました').check()
  await dialog.getByRole('button',{ name:'施設を保存する',exact:true }).click(); await expect(dialog).toHaveCount(0)
  const changed = await timelineState(page)
  for (const key of Object.keys(before)) if (key !== 'trips') expect(changed[key]).toEqual(before[key])
  expect(changed.trips!.find(t => t.id === 95000).currentZoneId).toBeUndefined()
  const graph = page.getByRole('region',{ name:'統合タイムライン',exact:true })
  await expect(graph.getByLabel('釣果・バラシのエリア').locator('option')).toContainText(['すべてのエリア','エリア未設定のみ','旧施設'])
  await expect(graph.locator('.catch-summary')).toContainText('0.75匹/時')
  await page.getByRole('region',{ name:'釣果履歴',exact:true }).getByRole('button',{ name:'編集',exact:true }).first().click()
  await expect(page.getByRole('dialog',{ name:'釣果を編集',exact:true }).getByText(/旧施設のエリアです/)).toBeVisible()
  await page.getByRole('dialog',{ name:'釣果を編集',exact:true }).getByRole('button',{ name:'キャンセル',exact:true }).click()
  await page.getByRole('button',{ name:'施設を設定・変更',exact:true }).click()
  await dialog.getByLabel('紐付ける正式施設').selectOption('official:nihon-iwana-center')
  await page.evaluate(() => { const put = IDBObjectStore.prototype.put; IDBObjectStore.prototype.put = function(...args:Parameters<IDBObjectStore['put']>) { if (this.name === 'trips') throw new DOMException('RC27保存障害','UnknownError'); return put.apply(this,args) } })
  await dialog.getByRole('button',{ name:'施設を保存する',exact:true }).click()
  await expect(dialog.getByRole('alert')).toContainText('RC27保存障害'); expect(await timelineState(page)).toEqual(changed)
})
