test('RC41 existing areas are reused explicitly, duplicate creation rolls back, and maps survive into another trip',async({page})=>{
  const base=rc41Fixture()
  await restoreViaUI(page,{...base,data:{...base.data,zones:[{id:'user:existing',facilityId:'user:rc41-f',name:'既存エリア',origin:'user'}]}})
  await page.locator('.trip-row[data-trip-id="1"]').click()
  const before=await state(page)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  const manager=page.getByRole('dialog',{name:'エリアマップ管理',exact:true})
  await manager.getByRole('button',{name:'＋エリアを追加',exact:true}).click()
  await manager.getByLabel('エリアマップ名（必須）',{exact:true}).fill('既存エリアのマップ')
  await manager.getByLabel('新規エリア名（必須）',{exact:true}).fill('既存エリア')
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('alert')).toContainText('同じ名称')
  expect(await state(page)).toEqual(before)
  await manager.getByLabel('関連するエリア',{exact:true}).selectOption('user:existing')
  await manager.getByRole('button',{name:'マップを保存',exact:true}).click()
  await expect(manager.getByRole('button',{name:'編集：既存エリアのマップ',exact:true})).toBeVisible()
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  expect((await state(page)).zones).toEqual(before.zones)
  await page.getByRole('button',{name:'← ホーム',exact:true}).click()
  await page.getByRole('button',{name:'新しい釣行を開始'}).click()
  await page.getByLabel('管理釣り場',{exact:true}).selectOption('user:rc41-f')
  await page.getByRole('button',{name:'🎣 釣行開始',exact:true}).click()
  await recordRc41Position(page,'既存エリアのマップ')
  const final=await state(page)
  expect(final.areaMaps).toHaveLength(1)
  expect(final.tripEvents!.at(-1)!.tripId).not.toBe(1)
  expect(final.tripEvents!.at(-1)!.fishingPosition.mapId).toBe(final.areaMaps![0]!.id)
  expect(final.catches).toEqual(before.catches)
})

test('RC41 map draft cancel, duplicate area, feature move/delete/undo and touch pinch/pan are reversible',async({page})=>{
  await restoreViaUI(page,rc41Fixture());await page.locator('.trip-row[data-trip-id="1"]').click()
  await createRc41Map(page,'ポンド')
  const before=await state(page)
  await page.getByRole('button',{name:'エリアマップ管理',exact:true}).click()
  const manager=page.getByRole('dialog',{name:'エリアマップ管理',exact:true})
  await manager.getByRole('button',{name:'編集：ポンド',exact:true}).click()
  const svg=manager.getByRole('img',{name:'ポンドのエリアマップ',exact:true})
  await manager.getByLabel('特徴物を選択',{exact:true}).selectOption({index:1})
  await dragMap(page,svg,[.3,.25],[.5,.25])
  await manager.getByRole('button',{name:'特徴物を削除',exact:true}).click()
  await expect(svg.locator('[data-feature-id]')).toHaveCount(1)
  await manager.getByRole('button',{name:'元に戻す',exact:true}).click()
  await expect(svg.locator('[data-feature-id]')).toHaveCount(2)
  // Chromium's actual touch input produces Pointer Events, including two simultaneous pointers.
  await svg.scrollIntoViewIfNeeded();const box=(await svg.boundingBox())!,cdp=await page.context().newCDPSession(page)
  const touch=(x:number,y:number,id:number)=>({x:box.x+box.width*x,y:box.y+box.height*y,id})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(.35,.5,0),touch(.65,.5,1)]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(.2,.5,0),touch(.8,.5,1)]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect(svg).not.toHaveAttribute('viewBox','0 0 1 1');await cdp.detach()
  const zoomed=await svg.getAttribute('viewBox');await dragMap(page,svg,[.5,.5],[.6,.5]);expect(await svg.getAttribute('viewBox')).not.toBe(zoomed)
  await manager.getByRole('button',{name:'キャンセル',exact:true}).click()
  await manager.getByRole('button',{name:'閉じる',exact:true}).click()
  expect(await state(page)).toEqual(before)
})
