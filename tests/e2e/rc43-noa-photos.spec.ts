import { readFile } from 'node:fs/promises'
import { test, expect, restoreViaUI, readAllState } from './fixtures'
import { rc43Fixture } from '../rc43Fixture'
import { openRc43Manager, uploadRc43Photo, openRc43CatchPicker, rc43Gold } from '../rc43UiHelpers'

test('RC43 individual external page is shared across models, opens separately and retains catch draft; SVG and owned filters remain usable', async ({ page, context }) => {
  await restoreViaUI(page, rc43Fixture())
  const before = await readAllState(page)
  const { modal, picker, card } = await openRc43CatchPicker(page)
  await expect(card.getByRole('img', { name: '配色プレビュー', exact: true })).toBeVisible()
  const link = card.getByRole('link', { name: '写真を見る', exact: true })
  await expect(link).toHaveAttribute('href', 'https://fishing-shop-jh.com/?pid=190933838')
  await expect(card.getByRole('link')).toHaveCount(1)
  await expect(card).toContainText('通信が必要')
  await context.route('https://fishing-shop-jh.com/**', route => route.fulfill({ contentType: 'text/html', body: '<title>Synthetic product page</title><p>Test only</p>' }))
  const [popup] = await Promise.all([page.waitForEvent('popup'), link.click()])
  await expect(popup).toHaveTitle('Synthetic product page'); await popup.close()
  await expect(modal.getByLabel('メモ（任意）', { exact: true })).toHaveValue('入力中のメモを保持')
  await expect(picker).toBeVisible(); expect(await readAllState(page)).toEqual(before)
  await picker.getByLabel('モデルを選んでからカラーを選択').selectOption('136')
  const jr = picker.locator(`[data-variant-id="${rc43Gold(136).id}"]`)
  await expect(jr.getByRole('link', { name: '写真を見る' })).toHaveAttribute('href', 'https://store.castingnet.jp/shop/g/g4571169081873/')
  await expect(jr.getByRole('link', { name: /その他の商品ページ/ })).toHaveAttribute('href', 'https://fishing-shop-jh.com/?pid=190933838')
  await picker.getByRole('checkbox', { name: '所有カラーのみ' }).check()
  await expect(picker).toContainText('該当するルアーがありません')
  await picker.getByRole('checkbox', { name: '所有カラーのみ' }).uncheck()
  await expect(jr).toBeVisible()
  await picker.getByRole('button', { name: 'SVG配色', exact: true }).click()
  await expect(jr.getByRole('link')).toHaveCount(0)
  await jr.getByRole('button', { name: /NOA Jr\. 0\.9g/ }).click()
  await expect(picker).not.toBeVisible()
  await expect(modal.getByLabel('メモ（任意）')).toHaveValue('入力中のメモを保持')
  expect(await readAllState(page)).toEqual(before)
})

test('RC43 user photo upload, front/back, shared family, zoom, replacement, deletion and photo archive round trip preserve existing records', async ({ page }, info) => {
  test.setTimeout(90000)
  await restoreViaUI(page, rc43Fixture())
  const before = await readAllState(page)
  const manager = await openRc43Manager(page)
  await expect(manager).toContainText('NOA Jr. 0.9g')
  await uploadRc43Photo(page); await uploadRc43Photo(page, { back: true })
  const [download] = await Promise.all([page.waitForEvent('download'), manager.getByText('写真のバックアップ', { exact: true }).click().then(() => manager.getByRole('button', { name: '写真バックアップを保存' }).click())])
  const path = info.outputPath('synthetic-noa-photos.json'); await download.saveAs(path)
  const archive = JSON.parse(await readFile(path, 'utf8'))
  expect(archive.photos).toHaveLength(2); expect(archive.blobs).toHaveLength(1); expect(archive.links).toHaveLength(8)
  await manager.getByRole('button', { name: '写真管理を閉じる' }).click()
  const dictionary = page.getByRole('dialog', { name: 'ビジュアルカラー辞書', exact: true })
  await dictionary.getByLabel('辞書モデル').selectOption('136')
  const jr = dictionary.locator(`article[data-variant-id="${rc43Gold(136).id}"]`)
  await jr.getByRole('button', { name: /表面写真を拡大/ }).click()
  const zoom = page.getByRole('dialog', { name: 'カラー写真の拡大', exact: true })
  await expect(zoom.getByRole('img')).toBeVisible(); await zoom.getByRole('button', { name: '写真を閉じる' }).click()
  await jr.getByRole('button', { name: '裏', exact: true }).click()
  await expect(jr.getByRole('img', { name: /裏面写真/ })).toBeVisible()
  await jr.getByRole('button', { name: 'カラー写真を管理' }).click()
  await manager.locator('.saved-photo').first().getByRole('button', { name: 'この写真を差し替え' }).click()
  await uploadRc43Photo(page, { red: 70 })
  await manager.getByText('写真のバックアップ', { exact: true }).click()
  // An older, conflicting photo archive must not overwrite the newer replacement.
  await manager.getByLabel('写真バックアップファイル').setInputFiles(path)
  await expect(manager.getByRole('status')).toContainText('競合')
  for (let i = 0; i < 2; i++) {
    await manager.locator('.saved-photo').first().getByRole('button', { name: 'この写真を削除' }).click()
    await expect(manager.locator('.saved-photo')).toHaveCount(1 - i)
    await expect(manager).toHaveAttribute('aria-busy', 'false')
  }
  await manager.getByLabel('写真バックアップファイル').setInputFiles(path)
  await expect(manager.getByRole('status')).toContainText('取り込みました')
  await manager.getByLabel('写真バックアップファイル').setInputFiles(path)
  await expect(manager.locator('.saved-photo')).toHaveCount(2)
  expect(await readAllState(page)).toEqual(before)
})
