import { readFile } from 'node:fs/promises'
import { test, expect, catalogFixture, restoreViaUI, startTrip, selectCatalog, saveCatch, readAllState } from './fixtures'
import { rc37Fixture } from '../rc37Fixture'
import { checkMaster, applyMaster, masterHome } from '../masterUiHelpers'

test('RC40 same-model colors, owned priority, cancel, deferred save, edit and backup round trip', async ({ page }, info) => {
  const fixture = catalogFixture()
  fixture.data.myLures.push({ id: 53, variantId: 41, active: true, ownershipStatus: 'owned' })
  fixture.data.lureModels.push({ id: 31, seriesId: 20, name: 'E2Eスプーン', category: 'スプーン' })
  fixture.data.lureVariants.push({ id: 42, modelId: 31, colorName: '別モデル専用色' })
  await restoreViaUI(page, fixture)
  await startTrip(page)
  const open = () => page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  const picker = page.getByRole('dialog', { name: 'カラーチェンジ', exact: true })
  await open()
  await expect(modal.getByRole('button', { name: 'カラーチェンジ' })).toBeDisabled()
  await selectCatalog(page, '青')
  await saveCatch(page)
  const before = await readAllState(page)
  await open()
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    const buttons = modal.locator('.quick-lure-actions button')
    for (const button of await buttons.all()) {
      const bounds = await button.boundingBox()
      expect(bounds!.height).toBeGreaterThanOrEqual(44)
      expect(bounds!.x).toBeGreaterThanOrEqual(0)
      expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
      expect(await button.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    }
  }
  await page.setViewportSize(info.project.use.viewport!)
  await modal.getByLabel('メモ（任意）').fill('カラー選択中も維持')
  await modal.getByLabel('全長（cm・任意）').fill('28')
  await modal.getByRole('button', { name: 'ボトム', exact: true }).click()
  await modal.getByRole('button', { name: 'カラーチェンジ' }).click()
  await expect(picker.locator('.picker-lure-button')).toHaveText(['青所有', '赤未所有'])
  await expect(picker).not.toContainText('別モデル専用色')
  await picker.getByLabel('カラーを検索').fill('見つからない')
  await expect(picker.getByRole('status')).toContainText('該当するカラーがありません')
  await picker.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await expect(modal.getByLabel('メモ（任意）')).toHaveValue('カラー選択中も維持')
  expect(await readAllState(page)).toEqual(before)
  await modal.getByRole('button', { name: 'カラーチェンジ' }).click()
  await picker.getByLabel('カラーを検索').fill('青')
  await picker.getByRole('button', { name: '青 所有', exact: true }).click()
  await expect(modal.locator('.selected-lure')).toContainText('青')
  await expect(modal.getByLabel('全長（cm・任意）')).toHaveValue('28')
  await expect(modal.getByRole('button', { name: 'ボトム', exact: true })).toHaveClass('selected')
  expect(await readAllState(page)).toEqual(before)
  await saveCatch(page)
  const changed = await readAllState(page)
  expect(changed.catches!.at(-1)).toMatchObject({ lureVariantId: 41, lureName: 'E2Eスプーン', lureColor: '青', memo: 'カラー選択中も維持', fishSizeCm: 28, rangeLevel: 'ボトム' })
  expect(changed.myLures).toEqual(before.myLures)
  expect(changed.catches![0]).toEqual(before.catches![0])
  // The existing shortcut still saves immediately.
  await open()
  await modal.getByRole('button', { name: '前回と同じ' }).click()
  await expect(modal).not.toBeVisible()
  expect((await readAllState(page)).catches!.at(-1)).toMatchObject({ lureVariantId: 41, lureColor: '青' })
  await open()
  await modal.getByRole('button', { name: 'カラーチェンジ' }).click()
  await picker.getByRole('button', { name: '赤 未所有', exact: true }).click()
  await saveCatch(page)
  expect((await readAllState(page)).catches!.at(-1)).toMatchObject({ lureVariantId: 40, lureColor: '赤' })
  expect((await readAllState(page)).myLures).toEqual(before.myLures)
  await page.getByRole('region', { name: '釣果履歴' }).getByRole('button', { name: '編集', exact: true }).first().click()
  const edit = page.getByRole('dialog', { name: '釣果を編集', exact: true })
  await expect(edit.getByRole('button', { name: 'カラーチェンジ' })).toHaveCount(0)
  await edit.getByLabel('メモ（任意）').fill('編集も維持')
  await edit.getByRole('button', { name: '保存する', exact: true }).click()
  await expect(edit).not.toBeVisible()
  const final = await readAllState(page)
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '📦 データをバックアップ', exact: true }).click()])
  const path = info.outputPath('rc40-backup.json')
  await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8'))
  await restoreViaUI(page, backup)
  expect(await readAllState(page)).toEqual(final)
})

test('RC40 bundled MOCA DR-F milk cocoa changes to tea without mixing rattle models', async ({ page }) => {
  test.setTimeout(90000)
  await restoreViaUI(page, rc37Fixture())
  await checkMaster(page); await applyMaster(page); await masterHome(page)
  const applied = await readAllState(page)
  const model = applied.lureModels!.find(m => m.name === 'MOCA DR-F 2HOOK')!
  const milk = applied.lureVariants!.find(v => v.modelId === model.id && v.colorName === 'ミルクココア')!
  const tea = applied.lureVariants!.find(v => v.modelId === model.id && v.colorName === 'さちおの茶')!
  expect(milk).toBeTruthy(); expect(tea).toBeTruthy()
  await page.locator('.trip-row[data-trip-id="1"]').click()
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: 'ルアーを選ぶ' }).click()
  const normal = page.getByRole('dialog', { name: 'ルアーを選択', exact: true })
  await normal.getByRole('button', { name: 'カタログ', exact: true }).click()
  await normal.getByLabel('モデルを選んでからカラーを選択').selectOption(String(model.id))
  await normal.getByRole('button', { name: /ミルクココア/ }).click()
  await saveCatch(page)
  const before = await readAllState(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await modal.getByRole('button', { name: 'カラーチェンジ' }).click()
  const picker = page.getByRole('dialog', { name: 'カラーチェンジ', exact: true })
  const colors = applied.lureVariants!.filter(v => v.modelId === model.id)
  await expect(picker.locator('.picker-lure-button')).toHaveCount(Math.min(colors.length, 50))
  await picker.getByLabel('カラーを検索').fill('さちおの茶')
  await picker.getByRole('button', { name: /^さちおの茶/ }).click()
  await saveCatch(page)
  const final = await readAllState(page)
  expect(final.catches!.at(-1)).toMatchObject({ lureVariantId: tea.id, lureName: model.name, lureColor: 'さちおの茶' })
  expect(final.myLures).toEqual(before.myLures)
  expect(final.catches!.slice(0, -1)).toEqual(before.catches)
})

test('RC40 legacy missing color resolves owned ID; manual latest and new trips disable color change', async ({ page }) => {
  const fixture = catalogFixture()
  fixture.data.trips.push({ id: 60, fishingAreaName: 'RC40旧記録', fishingDate: '2026-10-10', fishingStyle: 'AREA_TROUT', startedAt: '2026-10-10T00:00:00Z' })
  fixture.data.catches.push({ id: 70, tripId: 60, caughtAt: '2026-10-10T01:00:00Z', lureId: 50 })
  await restoreViaUI(page, fixture)
  await page.locator('.trip-row[data-trip-id="60"]').click()
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '釣果を登録', exact: true })
  await modal.getByRole('button', { name: 'カラーチェンジ' }).click()
  const picker = page.getByRole('dialog', { name: 'カラーチェンジ', exact: true })
  await expect(picker.locator('.picker-lure-button')).toHaveCount(2)
  await picker.getByRole('button', { name: '通常のルアー選択へ' }).click()
  await expect(page.getByRole('dialog', { name: 'ルアーを選択', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'マスターにないルアーを手入力' }).click()
  await modal.getByLabel('ルアー名', { exact: true }).fill('E2Eスプーン')
  await saveCatch(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await expect(modal.getByRole('button', { name: 'カラーチェンジ' })).toBeDisabled()
  await modal.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await page.getByRole('button', { name: '← ホーム', exact: true }).click()
  await startTrip(page)
  await page.getByRole('button', { name: '🎣 釣れた！', exact: true }).click()
  await expect(modal.getByRole('button', { name: 'カラーチェンジ' })).toBeDisabled()
})
