import { test, expect, restoreViaUI, readAllState } from './fixtures'
import { rc41Fixture } from '../rc41Fixture'
import { tapMap } from '../rc41UiHelpers'

test('RC41 actions sit below current area, never overlap, and have separate keyboard targets', async ({ page }, info) => {
  await restoreViaUI(page, rc41Fixture())
  await page.locator('.trip-row[data-trip-id="1"]').click()
  const section = page.getByRole('region', { name: '釣り座・エリアマップ', exact: true })
  const manage = section.getByRole('button', { name: 'エリアマップ管理', exact: true })
  const record = section.getByRole('button', { name: '釣り座を記録', exact: true })
  expect(await page.getByRole('group', { name: '現在のエリア', exact: true }).evaluate(el => el.nextElementSibling?.getAttribute('aria-label'))).toBe('釣り座・エリアマップ')
  await expect(manage).toHaveAccessibleDescription('ポンド・河川の形状や流れ込みを設定')
  await expect(record).toHaveAccessibleDescription('登録済みマップから現在の釣り座を指定')
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    const a = (await manage.boundingBox())!, b = (await record.boundingBox())!
    expect(a.height).toBeGreaterThanOrEqual(44)
    expect(b.height).toBeGreaterThanOrEqual(44)
    expect(b.y - (a.y + a.height)).toBeGreaterThanOrEqual(12)
    expect(a.x).toBeGreaterThanOrEqual(0)
    expect(b.x + b.width).toBeLessThanOrEqual(width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await section.screenshot({ path: info.outputPath('rc41-navigation-mobile.png') })
  await manage.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(manage).toBeFocused()
  expect(await manage.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('solid')
  await page.keyboard.press('Enter')
  const manager = page.getByRole('dialog', { name: 'エリアマップ管理', exact: true })
  await expect(manager).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(manager).not.toBeVisible()
  await manage.focus()
  await page.keyboard.press('Tab')
  await expect(record).toBeFocused()
  await page.keyboard.press('Space')
  await expect(page.getByRole('dialog', { name: 'イベント追加', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /エリアマップを作成/ })).toBeVisible()
})

test('RC41 empty-map shortcut preserves the event draft through cancel and creation, then saves normally', async ({ page }) => {
  await restoreViaUI(page, rc41Fixture())
  await page.locator('.trip-row[data-trip-id="1"]').click()
  const before = await readAllState(page)
  await page.getByRole('button', { name: '釣り座を記録', exact: true }).click()
  const event = page.getByRole('dialog', { name: 'イベント追加', exact: true })
  await event.getByLabel('発生日時（日本時間）').fill('2026-11-15T10:05')
  await event.getByLabel('メモ', { exact: true }).fill('マップ作成から戻っても保持')
  await event.getByRole('button', { name: /エリアマップを作成/ }).click()
  const manager = page.getByRole('dialog', { name: 'エリアマップ管理', exact: true })
  await expect(manager).toBeVisible()
  await manager.getByRole('button', { name: '閉じる', exact: true }).click()
  await expect(event.getByLabel('メモ', { exact: true })).toHaveValue('マップ作成から戻っても保持')
  await expect(event.getByLabel('発生日時（日本時間）')).toHaveValue('2026-11-15T10:05')
  expect(await readAllState(page)).toEqual(before)
  await event.getByRole('button', { name: /エリアマップを作成/ }).click()
  await manager.getByRole('button', { name: '＋エリアを追加', exact: true }).click()
  await manager.getByLabel('エリアマップ名（必須）', { exact: true }).fill('導線テストポンド')
  await manager.getByLabel('新規エリア名（必須）', { exact: true }).fill('導線テストポンド')
  await manager.getByRole('button', { name: 'マップを保存', exact: true }).click()
  await expect(manager.getByRole('button', { name: '編集：導線テストポンド', exact: true })).toBeVisible()
  await manager.getByRole('button', { name: '閉じる', exact: true }).click()
  await expect(event.getByLabel('メモ', { exact: true })).toHaveValue('マップ作成から戻っても保持')
  await expect(event.getByLabel('発生日時（日本時間）')).toHaveValue('2026-11-15T10:05')
  await expect(event.getByLabel('釣り座のエリアマップ', { exact: true })).toBeFocused()
  await expect(event.getByRole('button', { name: /エリアマップを作成/ })).toHaveCount(0)
  expect((await readAllState(page)).tripEvents).toEqual(before.tripEvents)
  await tapMap(event.getByRole('img', { name: '導線テストポンドのエリアマップ', exact: true }), .4, .24)
  await event.getByRole('button', { name: '保存', exact: true }).click()
  await expect(event).not.toBeVisible()
  const saved = await readAllState(page)
  expect(saved.tripEvents!.at(-1)).toMatchObject({ type: 'position', note: 'マップ作成から戻っても保持', occurredAt: '2026-11-15T01:05:00.000Z' })
  expect(saved.catches).toEqual(before.catches)
})
