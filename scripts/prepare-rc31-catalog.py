"""Freeze the reviewed CSV into the additive RC31 catalog. Never reads a backup."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader((ROOT / 'docs/rc31/palms_little_diner_83colors.csv').open(encoding='utf-8-sig')))
aliases = {'Powale': ['ポワレ', 'Little Diner Powale', 'リトルダイナー ポワレ'],
           'GANOFF': ['ガノフ', 'Little Diner GANOFF', 'リトルダイナー ガノフ'],
           'Galette': ['ガレット', 'Little Diner Galette', 'リトルダイナー ガレット']}
targets = {}
for row in rows:
    assert row['manufacturer'] == 'PALMS' and row['ownership'] == 'not_owned'
    assert row['evidence'] == 'manufacturer_official'
    model = row['model']
    target = dict(manufacturer='PALMS', manufacturerAliases=['パームス', 'PALMS（パームス）', 'パームス（PALMS）', '株式会社パームス'],
                  series=row['series'], seriesAliases=aliases[row['series']], model=model,
                  modelAliases=[row['series'] + ' ' + model, aliases[row['series']][0] + ' ' + model],
                  weight=float(row['weightG']), length=int(row['lengthMm']),
                  category={'トップウォーター': 'トップ', 'オーバーリップ': 'その他', 'クランク': 'クランク'}[row['category']],
                  actionType='F' if row['buoyancy'] == 'Floating' else 'S',
                  buoyancy=row['buoyancy'], sourceUrl=row['manufacturerUrl'])
    if model not in targets:
        targets[model] = dict(**target, colors=[])
    assert {k: v for k, v in targets[model].items() if k != 'colors'} == target
    targets[model]['colors'].append(dict(code=row['colorCode'], name=row['colorName'], label=f"{row['colorCode']} {row['colorName']}"))
assert [len(t['colors']) for t in targets.values()] == [12, 12, 7, 16, 16, 10, 10]
for t in targets.values():
    assert len({c['code'] for c in t['colors']}) == len(t['colors'])
header = """// Generated by scripts/prepare-rc31-catalog.py. Official spelling is preserved.
import type { LureCategory, LureModel } from '../db/database'
export interface Rc31Target {
  manufacturer: string; manufacturerAliases: string[]; series: string; seriesAliases: string[]
  model: string; modelAliases: string[]; weight: number; length: number; category: LureCategory
  actionType: LureModel['actionType']; buoyancy: string; sourceUrl: string
  colors: { code: string; name: string; label: string }[]
}
export const rc31Catalog: Rc31Target[] = """
(ROOT / 'src/data/rc31Catalog.ts').write_text(header + json.dumps(list(targets.values()), ensure_ascii=False, indent=2) + '\n', encoding='utf8')
