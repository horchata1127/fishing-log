import { readFile, writeFile } from 'node:fs/promises'
import { localTypeScript } from './load-local-typescript.mjs'

const directory = 'docs/lure-external-links/'
const baseline = JSON.parse(await readFile('docs/rodio-driftspin-bf/BASELINE.json'))
const previous = JSON.parse(await readFile('docs/rodio-driftspin-bf/ACCEPTED.json'))
const reviewed = JSON.parse(await readFile(directory + 'RODIO_REVIEW.json'))
const loader = await localTypeScript()
try {
  const { rc45RodioCatalog } = await loader.load('src/data/rc45RodioCatalog.ts')
  const refs = []
  for (const target of rc45RodioCatalog) {
    const compatible = baseline.models.filter(({ model }) => target.modelAliases.includes(model.name) && model.weightG === target.weight)
    for (const color of target.colors) {
      const evidence = previous.find(row => row.model === target.model && row.label === color.label && row.sourceUrl === color.sourceUrl)
      if (!evidence) throw new Error('Missing reviewed evidence for ' + color.label)
      const common = { manufacturerName: 'RODIO CRAFT', seriesName: target.series, colorName: color.label, colorCode: color.code || undefined,
        propertyEvidence: evidence.jan || undefined, sourceName: evidence.sourceName, sourceType: 'retailer', checkedAt: evidence.checkedAt,
        evidenceUrl: evidence.sourceUrl, verificationBasis: evidence.basis,
        product: { url: evidence.sourceUrl, verified: true, kind: evidence.colorClass === 'FORODOX(2026)' ? 'model-color-list' : 'individual-color' } }
      const models = [{ name: target.model, weightG: target.weight, lengthMm: target.length }, ...compatible.map(x => x.model)]
      for (const { name, weightG, lengthMm, actionType } of models) {
        const existing = baseline.models.find(row => row.model.name === name)
        const aliases = existing?.variants.filter(v => v.colorName === color.name || color.aliases.includes(v.colorName)).map(v => v.colorName) ?? []
        refs.push({ ...common, colorAliases: aliases.length ? aliases : undefined, modelName: name, modelDetails: { weightG, lengthMm, actionType } })
      }
    }
  }
  for (const evidence of reviewed.products) {
    const { manufacturer, series, model, modelDetails, color, colorCode, url, checkedAt, sourceName, basis, kind, jan } = evidence
    refs.push({ manufacturerName: manufacturer, seriesName: series, modelName: model, modelDetails,
      colorName: color, colorCode: colorCode || undefined, sourceName, sourceType: 'retailer', checkedAt, evidenceUrl: url,
      verificationBasis: basis, propertyEvidence: jan || undefined, product: { url, verified: true, kind } })
  }
  const key = r => JSON.stringify([r.seriesName, r.modelName, r.modelDetails, r.colorName])
  if (new Set(refs.map(key)).size !== refs.length) throw new Error('Duplicate reference identities')
  await writeFile('src/data/rodioExternalReferences.ts', '// Generated by scripts/build-rodio-rc47-references.mjs from audited product evidence.\n' +
    "import type { LureExternalReference } from './lureExternalReferences'\n\n" +
    'export const rodioExternalReferences: readonly LureExternalReference[] = [\n' +
    refs.map(ref => '  ' + JSON.stringify(ref) + ',').join('\n') + '\n]\n')
} finally {
  await loader.close()
}
